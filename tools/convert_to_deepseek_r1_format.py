# 思考链模板
THINKING_TEMPLATE = """
## 任务分析

1. **理解需求**：
   - 需要完成{task_type}任务
   - 核心要求是{core_requirement}

2. **确定技术方案**：
   - 需要使用光明语言{operations}相关的语法特性
   - 主要操作包括：{operations}

3. **代码设计**：
   - 变量命名：使用中文命名，清晰表达语义
   - 代码结构：按照逻辑顺序组织
   - 错误处理：考虑可能的异常情况

4. **实现步骤**：
   {steps}

5. **验证检查**：
   - 语法是否正确
   - 逻辑是否完整
   - 是否满足需求

## 思考完成，开始编写代码
"""

def generate_thinking(task_type, core_requirement, operations, steps):
    """生成思考链"""
    return THINKING_TEMPLATE.format(
        task_type=task_type,
        core_requirement=core_requirement,
        operations=operations,
        steps="\n   - ".join(steps)
    )

