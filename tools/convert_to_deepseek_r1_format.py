def convert_to_deepseek_r1_format():
    """将示例数据转换为 DeepSeek R1 格式"""
    output_lines = []
    for example in examples:
        task = example["task"]
        code = example["code"]

        # 提取任务类型和核心要求
        task_type = "编程任务"
        if "变量" in task:
            task_type = "变量与类型操作"
        elif "列表" in task:
            task_type = "列表操作"
        elif "字典" in task:
            task_type = "字典操作"
        elif "条件" in task:
            task_type = "条件判断"
        elif "循环" in task:
            task_type = "循环控制"
        elif "函数" in task:
            task_type = "函数定义"
        elif "类" in task:
            task_type = "面向对象"
        elif "文件" in task:
            task_type = "文件操作"
        elif "JSON" in task or "json" in task:
            task_type = "JSON处理"
        elif "网络" in task or "HTTP" in task or "请求" in task:
            task_type = "网络请求"
        elif "统计" in task or "平均" in task or "和" in task:
            task_type = "统计计算"
        elif "随机" in task:
            task_type = "随机数"
        elif "日志" in task or "配置" in task or "缓存" in task or "进度条" in task:
            task_type = "工具函数"
        elif "断言" in task or "参数" in task or "类型" in task:
            task_type = "实用工具"
        elif "综合" in task:
            task_type = "综合应用"

        # 提取操作
        operations = []
        if "拼接" in task:
            operations.append("字符串拼接")
        if "分割" in task:
            operations.append("字符串分割")
        if "替换" in task:
            operations.append("字符串替换")
        if "排序" in task:
            operations.append("列表排序")
        if "求和" in task or "平均" in task:
            operations.append("统计计算")
        if "写入" in task or "读取" in task:
            operations.append("文件读写")
        if "JSON" in task:
            operations.append("JSON序列化/解析")
        if "请求" in task:
            operations.append("HTTP请求")
        if not operations:
            operations.append("基本操作")

        # 提取步骤
        steps = []
        if "定义" in task or "创建" in task:
            steps.append("定义变量/数据结构")
        if "打印" in task or "输出" in task:
            steps.append("输出结果")
        if "判断" in task or "计算" in task:
            steps.append("执行计算或判断")
        if "遍历" in task or "循环" in task:
            steps.append("遍历或循环")
        if "函数" in task or "类" in task:
            steps.append("定义函数或类")
        if "保存" in task or "写入" in task:
            steps.append("保存结果")
        if not steps:
            steps.append("执行基本操作")

        # 生成思考链
        thinking = generate_thinking(
            task_type=task_type,
            core_requirement=task,
            operations=", ".join(operations),
            steps=steps
        )

        # 构建 DeepSeek R1 格式
        data = {
            "instruction": task,
            "thinking": thinking,
            "response": code
        }

        output_lines.append(json.dumps(data, ensure_ascii=False))

    return output_lines

def main():
    """主函数"""
    # 转换数据
    output_lines = convert_to_deepseek_r1_format()

    # 写入文件
    output_file = Path("docs/dataset_deepseek_r1_100_examples.jsonl")
    output_file.parent.mkdir(parents=True, exist_ok=True)

    with open(output_file, "w", encoding="utf-8", newline="\n") as f:
        for line in output_lines:
            f.write(line + "\n")

    print(f"✅ 转换完成！共 {len(output_lines)} 条数据")
    print(f"📄 输出文件：{output_file}")
    print(f"📊 数据格式：DeepSeek R1（带思考链）")
    print(f"📝 每条数据包含：instruction（任务）、thinking（思考链）、response（代码）")

    # 显示前3条数据示例
    print("\n📋 前3条数据示例：")
    for i, line in enumerate(output_lines[:3]):
        data = json.loads(line)
        print(f"\n--- 示例 {i+1} ---")
        print(f"任务：{data['instruction'][:50]}...")
        print(f"思考链长度：{len(data['thinking'])} 字符")
        print(f"代码长度：{len(data['response'])} 字符")

if __name__ == "__main__":
    main()
