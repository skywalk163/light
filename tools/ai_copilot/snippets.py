def list_snippets() -> str:
    """列出所有片段的名称和描述"""
    lines = []
    for name, info in SNIPPETS.items():
        placeholders = ", ".join(info.get("placeholders", {}).keys())
        lines.append(f"  {name:20s} | {info['desc']} | 占位符: {placeholders}")
    return "\n".join(lines)


def get_snippet(name: str) -> Optional[Dict]:
    """按名称获取片段"""
    return SNIPPETS.get(name)


def expand_snippet(name: str, **kwargs) -> str:
    """填充片段的占位符

    Args:
        name: 片段名称
        **kwargs: 占位符名→值的映射（不带 __ 包裹）

    Returns:
        填充后的代码文本

    Example:
        expand_snippet("段落-带返回值", 段名="加法", 参数="a, b", 返回值="a 加 b")
    """
    snippet = SNIPPETS.get(name)
    if not snippet:
        raise KeyError(f"片段不存在: {name}")

    code = snippet["code"]
    for key, value in kwargs.items():
        code = code.replace(f"__{key}__", str(value))
    return code


def get_snippets_prompt() -> str:
    """生成可嵌入 prompt 的片段库描述"""
    lines = ["【光明代码片段库】", ""]
    for name, info in SNIPPETS.items():
        lines.append(f"片段：{name}")
        lines.append(f"  用途：{info['desc']}")
        lines.append(f"  模板：{info['code']}")
        if "example" in info:
            lines.append(f"  示例：{info['example']}")
        if "pitfall" in info:
            lines.append(f"  ⚠暗坑：{info['pitfall']}")
        lines.append("")
    return "\n".join(lines)


