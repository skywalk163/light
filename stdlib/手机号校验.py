# 手机号正则：1 开头，后跟 10 位数字
_PHONE_PATTERN = re.compile(r'^1\d{10}$')


class ChinesePhoneValidator:
    """中国手机号码校验器

    支持 11 位手机号码的格式校验、运营商识别和归属地查询。
    内置移动、联通、电信、广电、虚拟运营商的号段映射。

    用法:
        validator = ChinesePhoneValidator()
        result = validator.validate("13800138000")
        # result = {"valid": True, "carrier": "中国移动", "region": "北京", "phone": "13800138000"}
    """

    def validate(self, phone: str) -> Dict[str, object]:
        """校验手机号码并返回详细信息

        对 11 位手机号码进行完整性校验，包括：
        - 格式检查（长度、字符）
        - 号段有效性验证
        - 运营商和归属地识别

        Args:
            phone: 11 位手机号码

        Returns:
            校验结果字典:
            - valid: 是否有效
            - phone: 手机号码
            - carrier: 运营商名称
            - region: 归属地（省份）
            - errors: 错误信息列表（无效时）
        """
        errors = []

        if not phone:
            errors.append("手机号码不能为空")
            return self._make_error_result(errors)

        if not _PHONE_PATTERN.match(phone):
            if len(phone) != 11:
                errors.append("手机号码必须为11位")
            elif not phone.isdigit():
                errors.append("手机号码只能包含数字")
            else:
                errors.append("手机号码格式不正确（必须以1开头）")
            return self._make_error_result(errors)

        # 识别运营商
        carrier = self.get_carrier(phone)
        if not carrier:
            errors.append(f"未知号段: {phone[:3]}")

        # 识别归属地
        region = self._lookup_region(phone)

        if errors:
            return {
                "valid": False,
                "phone": phone,
                "carrier": carrier or "",
                "region": region or "",
                "errors": errors,
            }

        return {
            "valid": True,
            "phone": phone,
            "carrier": carrier,
            "region": region or "未知",
            "errors": [],
        }

    def get_carrier(self, phone: str) -> str:
        """获取手机号码的运营商

        根据手机号码的前 3 位号段识别运营商。
        支持中国移动、中国联通、中国电信、中国广电和虚拟运营商。

        Args:
            phone: 11 位手机号码

        Returns:
            运营商名称（如 "中国移动"），未知号段返回空字符串
        """
        if not phone or len(phone) < 3:
            return ""
        prefix = phone[:3]
        return _CARRIER_MAP.get(prefix, "")

    def get_region(self, phone: str) -> str:
        """获取手机号码的归属地（简化版）

        根据手机号码的前 4 位查询归属地省份。
        注意：此方法为简化版，实际归属地需要更精确的号段数据库。

        Args:
            phone: 11 位手机号码

        Returns:
            归属地省份名称，未知返回空字符串
        """
        if not phone or len(phone) < 4:
            return ""
        return self._lookup_region(phone)

    # ------------------------------------------------------------------
    # 内部辅助方法
    # ------------------------------------------------------------------

    @staticmethod
    def _lookup_region(phone: str) -> str:
        """根据手机号前 4 位查询归属地

        Args:
            phone: 11 位手机号码

        Returns:
            省份名称，未找到返回空字符串
        """
        if len(phone) < 4:
            return ""
        key = phone[:4]
        # 直接匹配 4 位前缀
        if key in _REGION_PREFIX_MAP:
            return _REGION_PREFIX_MAP[key]
        # 回退到前 3 位省份推断（返回空，因为 3 位号段无法精确判断省份）
        return ""

    @staticmethod
    def _make_error_result(errors: list) -> Dict[str, object]:
        """构建错误结果字典

        Args:
            errors: 错误信息列表

        Returns:
            包含错误信息的结果字典
        """
        return {
            "valid": False,
            "phone": "",
            "carrier": "",
            "region": "",
            "errors": errors,
        }


