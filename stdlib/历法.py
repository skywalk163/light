def 公历转农历(年, 月, 日):
    """
    公历日期转农历日期。
    
    返回: 字典 {年, 月, 日, 闰月}
    """
    if not _HAS_LUNAR:
        raise RuntimeError("农历转换需要 lunardate 库，请执行: pip install lunardate")
    
    lunar = _LunarDate.from_solar_date(年, 月, 日)
    return {
        '年': lunar.year,
        '月': lunar.month,
        '日': lunar.day,
        '闰月': lunar.isLeapMonth,
    }


def 农历转公历(年, 月, 日, 闰月=False):
    """
    农历日期转公历日期。
    
    参数:
        闰月: 该月是否为闰月
    
    返回: 字典 {年, 月, 日}
    """
    if not _HAS_LUNAR:
        raise RuntimeError("农历转换需要 lunardate 库，请执行: pip install lunardate")
    
    lunar = _LunarDate(年, 月, 日, is_leap_month=闰月)
    solar = lunar.to_solar_date()
    return {
        '年': solar.year,
        '月': solar.month,
        '日': solar.day,
    }


