def 生肖(年):
    """
    获取公历年份对应的生肖。
    
    参数:
        年: 公历年份
    
    返回: 生肖字符（如"马"）
    
    注意: 以立春为分界，这里简化为以公历年计算。
          已知 2020 年为鼠年。
    """
    # 2020 = 鼠 = 地支子 = index 0
    offset = (年 - 2020) % 12
    return _ZODIAC_ANIMALS[offset]


