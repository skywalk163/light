_LUNAR_DAY_NAMES = [
    '初一', '初二', '初三', '初四', '初五', '初六', '初七', '初八', '初九', '初十',
    '十一', '十二', '十三', '十四', '十五', '十六', '十七', '十八', '十九', '二十',
    '廿一', '廿二', '廿三', '廿四', '廿五', '廿六', '廿七', '廿八', '廿九', '三十',
]

_LUNAR_MONTH_NAMES = ['正', '二', '三', '四', '五', '六', '七', '八', '九', '十', '冬', '腊']


def 农历月名(月, 闰月=False):
    """
    获取农历月份名称。
    
    参数:
        月: 农历月份 1-12
        闰月: 是否为闰月
    
    返回: 月份名（如"正月"、"闰四月"）
    """
    if 月 < 1 or 月 > 12:
        raise ValueError("农历月份必须在 1-12 之间")
    
    name = _LUNAR_MONTH_NAMES[月 - 1] + "月"
    if 闰月:
        name = "闰" + name
    return name


def 农历日名(日):
    """
    获取农历日名称。
    
    参数:
        日: 农历日 1-30
    
    返回: 日名（如"初一"、"十五"、"廿三"）
    """
    if 日 < 1 or 日 > 30:
        raise ValueError("农历日必须在 1-30 之间")
    return _LUNAR_DAY_NAMES[日 - 1]


def 农历完整日期(年, 月, 日, 闰月=False):
    """
    获取农历日期的完整中文名称。
    
    返回: 如"丙午年六月二十"
    """
    year_ganzhi = 干支纪年(年)
    month_name = 农历月名(月, 闰月)
    day_name = 农历日名(日)
    zodiac = 生肖(年)
    
    return f"{year_ganzhi}{zodiac}年{month_name}{day_name}"


