_HEAVENLY_STEMS = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸']
_EARTHLY_BRANCHES = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥']
_ZODIAC_ANIMALS = ['鼠', '牛', '虎', '兔', '龙', '蛇', '马', '羊', '猴', '鸡', '狗', '猪']


def 天干(序号):
    """
    获取天干。
    
    参数:
        序号: 0-9（0=甲, 1=乙, ...）
    
    返回: 天干字符
    """
    if 序号 < 0 or 序号 > 9:
        raise ValueError("天干序号必须在 0-9 之间")
    return _HEAVENLY_STEMS[序号]


def 地支(序号):
    """
    获取地支。
    
    参数:
        序号: 0-11（0=子, 1=丑, ...）
    
    返回: 地支字符
    """
    if 序号 < 0 or 序号 > 11:
        raise ValueError("地支序号必须在 0-11 之间")
    return _EARTHLY_BRANCHES[序号]


def 干支(序号):
    """
    获取干支（六十甲子）。
    
    参数:
        序号: 0-59
    
    返回: 干支字符串（如"甲子"）
    """
    if 序号 < 0 or 序号 > 59:
        raise ValueError("干支序号必须在 0-59 之间")
    stem = _HEAVENLY_STEMS[序号 % 10]
    branch = _EARTHLY_BRANCHES[序号 % 12]
    return stem + branch


def 干支纪年(年):
    """
    获取公历年份的干支纪年。
    
    参数:
        年: 公历年份
    
    返回: 干支字符串（如"丙午"）
    
    注意: 以立春为分界，这里简化为以公历年计算。
          已知 1984 年为甲子年。
    """
    # 1984 = 甲子年 = 干支序号 0
    offset = (年 - 1984) % 60
    return 干支(offset)


def 干支纪月(年, 月):
    """
    获取公历年月的干支纪月。
    
    返回: 干支字符串
    """
    # 以立春为寅月（正月）开始
    # 1998 年立春后第一个月为甲寅月
    # 年干定月干：甲己之年丙作首，乙庚之岁戊为头，
    #             丙辛之岁寻庚起，丁壬壬位顺行流，
    #             戊癸甲寅好追求
    year_stem = (年 - 1984) % 10
    
    # 月支：寅为正月（约2月），卯为二月，...
    # 公历1月 ≈ 丑月（十二月）
    month_branch_offset = (月 + 1) % 12  # 1月->丑(1), 2月->寅(2)
    
    # 月干：根据年干推算
    # 甲己年: 正月丙寅 = stem_index 2
    # 乙庚年: 正月戊寅 = stem_index 4
    # 丙辛年: 正月庚寅 = stem_index 6
    # 丁壬年: 正月壬寅 = stem_index 8
    # 戊癸年: 正月甲寅 = stem_index 0
    base_stem_map = [2, 4, 6, 8, 0]
    base_stem = base_stem_map[year_stem % 5]
    month_stem = (base_stem + (月 - 1)) % 10
    
    # 月支
    branch_idx = (月 + 1) % 12  # 1月=丑(1), 2月=寅(2)
    
    return _HEAVENLY_STEMS[month_stem] + _EARTHLY_BRANCHES[branch_idx]


def 干支纪日(年, 月, 日):
    """
    获取公历日期的干支纪日。
    
    基于已知基准日推算。
    已知: 1900年1月1日为甲戌日（干支序号 10）。
    
    返回: 干支字符串
    """
    from datetime import date
    
    base = date(1900, 1, 1)
    target = date(年, 月, 日)
    days_diff = (target - base).days
    
    offset = (10 + days_diff) % 60
    return 干支(offset)


