# 按词长降序排序，确保最大匹配优先
_BUILTIN_DICT.sort(key=lambda x: len(x), reverse=True)


class ChineseTokenizer:
    """基于正向最大匹配算法的中文分词器

    从文本左侧开始，每次尝试匹配词典中最长的词。
    匹配失败时按单字切分并继续。

    用法:
        tokenizer = ChineseTokenizer()
        words = tokenizer.segment("今天天气真不错")
        # words = ["今天", "天气", "真不错"]

        tokenizer.add_word("自定义词")
        words = tokenizer.segment("包含自定义词的文本")

        tokenizer.load_dict(["词1", "词2", "词3"])
        words = tokenizer.segment("加载词典后的文本")
    """

    def __init__(self):
        """初始化分词器，加载内置词典"""
        self._dict = set(_BUILTIN_DICT)
        self._max_word_len = max(len(w) for w in self._dict) if self._dict else 0

    def segment(self, text: str) -> List[str]:
        """对输入文本进行分词

        使用正向最大匹配算法（Maximum Matching）从左到右扫描文本，
        每次从当前位置取最长可能的匹配词，匹配失败则按单字切分。

        Args:
            text: 待分词的中文文本

        Returns:
            分词后的词语列表
        """
        if not text:
            return []

        result: List[str] = []
        i = 0
        text_len = len(text)

        while i < text_len:
            matched = False
            # 从最大词长开始尝试匹配
            for j in range(min(self._max_word_len, text_len - i), 0, -1):
                word = text[i:i + j]
                if word in self._dict:
                    result.append(word)
                    i += j
                    matched = True
                    break

            if not matched:
                # 匹配失败，按单字切分
                result.append(text[i])
                i += 1

        return result

    def add_word(self, word: str) -> None:
        """添加自定义词到词典

        添加后自动更新最大词长，确保新词能被正确匹配。

        Args:
            word: 要添加的词语
        """
        if word:
            self._dict.add(word)
            if len(word) > self._max_word_len:
                self._max_word_len = len(word)

    def load_dict(self, words: List[str]) -> None:
        """加载词典，批量添加词语

        替换当前词典（不清除内置词典），而是扩展词典。
        批量添加后自动更新最大词长。

        Args:
            words: 词语列表
        """
        for word in words:
            if word:
                self._dict.add(word)
                if len(word) > self._max_word_len:
                    self._max_word_len = len(word)

    @property
    def dictionary(self) -> set:
        """获取当前词典的只读视图"""
        return set(self._dict)

    @property
    def vocabulary_size(self) -> int:
        """获取词典大小"""
        return len(self._dict)


# =============================================================================
# 便捷函数
# =============================================================================

_default_tokenizer = ChineseTokenizer()


def 分词(text: str) -> List[str]:
    """使用默认分词器快速分词

    便捷函数，内部使用全局默认的 ChineseTokenizer 实例。

    Args:
        text: 待分词的中文文本

    Returns:
        分词后的词语列表
    """
    return _default_tokenizer.segment(text)


def 添加自定义词(word: str) -> None:
    """向默认分词器添加自定义词

    Args:
        word: 要添加的词语
    """
    _default_tokenizer.add_word(word)


def 加载词典(words: List[str]) -> None:
    """向默认分词器加载词典

    Args:
        words: 词语列表
    """
    _default_tokenizer.load_dict(words)


