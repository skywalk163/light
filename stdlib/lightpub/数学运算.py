"""
数学运算 — lightpub 桥接模块

基于 Python math 库封装，提供数学运算功能。

上游 duanpub 原始包通过 C FFI 调用 C 数学库，
本桥接模块用 Python math 模块替代，提供等价的数学运算功能。
"""

import math as _math


# =============================================================================
# 常量
# =============================================================================

圆周率 = _math.pi
自然常数 = _math.e
无穷大 = _math.inf
负无穷 = -_math.inf
非数字 = _math.nan


# =============================================================================
# 基本运算
# =============================================================================

def 平方根(x):
    """平方根"""
    if x < 0:
        raise Exception("平方根失败: 不能对负数求平方根")
    return _math.sqrt(x)


def 绝对值(x):
    """绝对值"""
    return abs(x)


def 幂运算(底数, 指数):
    """幂运算（底数的指数次方）"""
    try:
        return _math.pow(底数, 指数)
    except (ValueError, OverflowError) as e:
        raise Exception("幂运算失败: " + str(e))


def 取模(a, b):
    """取模运算"""
    if b == 0:
        raise Exception("取模失败: 除数不能为零")
    return a % b


def 符号函数(x):
    """符号函数，返回 -1/0/1"""
    if x > 0:
        return 1
    elif x < 0:
        return -1
    return 0


# =============================================================================
# 取整函数
# =============================================================================

def 向下取整(x):
    """向下取整"""
    return _math.floor(x)


def 向上取整(x):
    """向上取整"""
    return _math.ceil(x)


def 取整(x):
    """截断取整（向零方向）"""
    return _math.trunc(x)


# =============================================================================
# 最大最小值
# =============================================================================

def 最大值(*值):
    """取最大值"""
    if not 值:
        raise Exception("最大值失败: 参数为空")
    return max(值)


def 最小值(*值):
    """取最小值"""
    if not 值:
        raise Exception("最小值失败: 参数为空")
    return min(值)


def 最大公约数(a, b):
    """最大公约数"""
    return _math.gcd(int(a), int(b))


def 最小公倍数(a, b):
    """最小公倍数"""
    if a == 0 or b == 0:
        return 0
    return abs(a * b) // _math.gcd(int(a), int(b))


# =============================================================================
# 对数与指数
# =============================================================================

def 自然对数(x):
    """自然对数（以 e 为底）"""
    if x <= 0:
        raise Exception("自然对数失败: 参数必须大于零")
    return _math.log(x)


def 对数(x, 底=_math.e):
    """对数（指定底）"""
    if x <= 0:
        raise Exception("对数失败: 参数必须大于零")
    if 底 <= 0 or 底 == 1:
        raise Exception("对数失败: 底必须大于零且不等于1")
    return _math.log(x, 底)


def 二进制对数(x):
    """二进制对数（以 2 为底）"""
    if x <= 0:
        raise Exception("二进制对数失败: 参数必须大于零")
    return _math.log2(x)


def 十进制对数(x):
    """十进制对数（以 10 为底）"""
    if x <= 0:
        raise Exception("十进制对数失败: 参数必须大于零")
    return _math.log10(x)


def 指数(x):
    """指数函数（e 的 x 次方）"""
    try:
        return _math.exp(x)
    except OverflowError:
        raise Exception("指数失败: 溢出")


# =============================================================================
# 三角函数
# =============================================================================

def 正弦(x):
    """正弦（弧度）"""
    return _math.sin(x)


def 余弦(x):
    """余弦（弧度）"""
    return _math.cos(x)


def 正切(x):
    """正切（弧度）"""
    try:
        return _math.tan(x)
    except ValueError:
        raise Exception("正切失败: 无效输入")


def 反正弦(x):
    """反正弦，返回弧度"""
    if x < -1 or x > 1:
        raise Exception("反正弦失败: 参数必须在 -1 到 1 之间")
    return _math.asin(x)


def 反余弦(x):
    """反余弦，返回弧度"""
    if x < -1 or x > 1:
        raise Exception("反余弦失败: 参数必须在 -1 到 1 之间")
    return _math.acos(x)


def 反正切(x):
    """反正切，返回弧度"""
    return _math.atan(x)


def 反正切2(y, x):
    """反正切（双参数），返回弧度"""
    return _math.atan2(y, x)


# =============================================================================
# 双曲函数
# =============================================================================

def 双曲正弦(x):
    """双曲正弦"""
    return _math.sinh(x)


def 双曲余弦(x):
    """双曲余弦"""
    return _math.cosh(x)


def 双曲正切(x):
    """双曲正切"""
    return _math.tanh(x)


# =============================================================================
# 角度弧度转换
# =============================================================================

def 弧度转角度(弧度):
    """弧度转角度"""
    return _math.degrees(弧度)


def 角度转弧度(角度):
    """角度转弧度"""
    return _math.radians(角度)


# =============================================================================
# 特殊函数
# =============================================================================

def 阶乘(n):
    """阶乘（n!）"""
    if n < 0:
        raise Exception("阶乘失败: 参数不能为负")
    return _math.factorial(int(n))


def 伽马函数(x):
    """伽马函数"""
    if x <= 0 and x == int(x):
        raise Exception("伽马函数失败: 非正整数无定义")
    return _math.gamma(x)


def 阶乘对数(n):
    """阶乘的自然对数（log(n!)）"""
    if n < 0:
        raise Exception("阶乘对数失败: 参数不能为负")
    return _math.lgamma(int(n))


def 误差函数(x):
    """误差函数"""
    return _math.erf(x)


def 互补误差函数(x):
    """互补误差函数"""
    return _math.erfc(x)


# =============================================================================
# 判断函数
# =============================================================================

def 是有限值(x):
    """判断是否为有限值"""
    return _math.isfinite(x)


def 是无穷大(x):
    """判断是否为无穷大"""
    return _math.isinf(x)


def 是非数字(x):
    """判断是否为 NaN"""
    return _math.isnan(x)


def 是否接近(a, b, 相对容差=1e-9, 绝对容差=0.0):
    """判断两个数是否接近"""
    return _math.isclose(a, b, rel_tol=相对容差, abs_tol=绝对容差)


# =============================================================================
# 其他
# =============================================================================

def 复制符号(x, y):
    """返回 |x| 带 y 的符号"""
    return _math.copysign(x, y)


def 余数(x, y):
    """浮点余数（与 x 同号）"""
    if y == 0:
        raise Exception("余数失败: 除数不能为零")
    return _math.fmod(x, y)


def 求和(列表):
    """求列表元素之和"""
    return sum(列表)


def 平均值(列表):
    """求列表元素平均值"""
    if not 列表:
        raise Exception("平均值失败: 列表为空")
    return sum(列表) / len(列表)


def 标准差(列表, 总体=True):
    """求标准差（总体默认 True，样本设为 False）"""
    if not 列表:
        raise Exception("标准差失败: 列表为空")
    if len(列表) < 2 and not 总体:
        raise Exception("标准差失败: 样本至少需要2个元素")
    n = len(列表)
    平均 = sum(列表) / n
    方差和 = sum((x - 平均) ** 2 for x in 列表)
    除数 = n if 总体 else (n - 1)
    return _math.sqrt(方差和 / 除数)
