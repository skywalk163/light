def 转条目(d):
    e = {
        '名称': d['名称'],
        '领域': d['领域'],
        '层级': d.get('层级', 0),
        '描述': d['描述'],
        '输入': [{'名': n, '类型': t} for n, t in d['输入']],
        '输出': {'类型': d['输出']},
        '稳定性': d.get('稳定性', 'stable'),
        '路径': d['路径'],
        '导出名': d['导出名'],
    }
    if d.get('样例'):
        e['样例'] = d['样例']
    if d.get('期望') is not None:
        e['期望'] = d['期望']
    return e


def main():
    p = os.path.join(_HERE, '索引.json')
    idx = json.load(io.open(p, encoding='utf-8'))
    有 = {b['名称'] for b in idx['块']}
    加 = 0
    for d in 新块:
        if d['名称'] in 有:
            continue
        idx['块'].append(转条目(d))
        加 += 1
    io.open(p, 'w', encoding='utf-8').write(
        json.dumps(idx, ensure_ascii=False, indent=2) + '\n')
    print('新增 %d 块，现共 %d 块' % (加, len(idx['块'])))


if __name__ == '__main__':
    main()
