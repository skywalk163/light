# 中文数字 → 阿拉伯（仅用于块名归一，规避词法器把中文数字当普通字符切开的潜在坑）
_中文数数字 = {'零': 0, '〇': 0, '一': 1, '二': 2, '两': 2, '三': 3, '四': 4,
            '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}
_中文数位权 = {'十': 10, '百': 100, '千': 1000}
_中文数节权 = {'万': 10000, '亿': 100000000}


def _解析中文整数(串):
    """把一段连续中文数字（含 十/百/千/万/亿）解析为 int；含『点』或非法字符返回 None。"""
    总 = 0
    节 = 0
    当前 = 0
    for 字 in 串:
        if 字 == '点':
            return None
        if 字 in _中文数数字:
            当前 = _中文数数字[字]
        elif 字 in _中文数位权:
            if 当前 == 0:
                当前 = 1
            节 += 当前 * _中文数位权[字]
            当前 = 0
        elif 字 in _中文数节权:
            节 += 当前
            总 += (节 if 节 else 1) * _中文数节权[字]
            节 = 0
            当前 = 0
        else:
            return None
    总 += 节 + 当前
    return 总


def _中文数字归一(名):
    """块名里成段的中文数字转阿拉伯；带『点』的小数段保持原样（词法器可识别）。"""
    out = []
    i = 0
    n = len(名)
    while i < n:
        字 = 名[i]
        if 字 in _中文数数字 or 字 in _中文数位权 or 字 in _中文数节权:
            j = i
            while j < n and (名[j] in _中文数数字 or 名[j] in _中文数位权
                             or 名[j] in _中文数节权):
                j += 1
            段 = 名[i:j]
            值 = _解析中文整数(段)
            out.append(str(值) if 值 is not None else 段)
            i = j
        else:
            out.append(字)
            i += 1
    return ''.join(out)


def _归一块名(名):
    """把块名清成合法标识符；返回 (新名, 是否改动)。

    归一顺序：先中文数字→阿拉伯（防词法器坑），再去非法字符，最后若以数字开头加『块』前缀。
    """
    原 = 名 or ''
    新 = _中文数字归一(原)
    新 = _名非法.sub('', 新)
    if 新 and 新[0].isdigit():
        新 = '块' + 新
    return (新 or '生成块'), (新 != 原)


def _安全名(名):
    """把积木名净化成安全文件名基名（防御性净化落点）。

    块名来自 LLM 返回（不可信），可能携带 ``../`` 、绝对路径或非法字符；
    写入/删除 生成/ 下的 .light 前必须净化为合法基名，杜绝路径穿越。
    """
    新, _ = _归一块名(名)
    # 双保险：_归一块名 已剔除非法字符，这里再显式剔除路径分隔符与父目录记号，并限长
    新 = 新.replace(os.sep, '').replace('/', '').replace('\\', '').replace('..', '')
    return 新[:64]


