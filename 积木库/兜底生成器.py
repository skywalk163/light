def _选范例(需求, k=1):
    """按需求关键词重合度召回最相关的范例块（默认只取最相关 1 个，避免多个相似体积/面积范例互相带偏）。"""
    scored = []
    for ex in _范例库:
        s = sum(1 for kw in ex["关键词"] if kw in 需求)
        if s > 0:
            scored.append((s, ex["块"]))
    scored.sort(key=lambda x: -x[0])
    return [b for _, b in scored[:k]]


def _call_llm(需求, 候选, cfg):
    if not cfg.get('api_key'):
        return None, None
    url = cfg['base_url'].rstrip('/') + '/chat/completions'
    exs = _选范例(需求)
    if exs:
        # 已有高相关范例指引：抑制可能错误的库内候选，避免把 LLM 带偏
        # （如「圆柱体积」被候选「球体积」带成生成「球体积示例」）。
        cands = '（无，见下方参考范例）'
    else:
        cands = '、'.join(c.get('名称', '') for c in (候选 or [])[:5]) or '（无）'
    ex_text = ''
    for b in exs:
        ex_text += '\n【参考范例·与本条需求同类型，请照此模式生成，块名自拟勿照抄】%s' % json.dumps(b, ensure_ascii=False)
    user = '需求：%s\n已选候选（可能不对）：%s\n请生成一块能直接满足该需求的段言积木。%s' % (需求, cands, ex_text)
    payload = {
        'model': cfg['model'],
        'messages': [
            {'role': 'system', 'content': _SYSTEM},
            {'role': 'user', 'content': user},
        ],
        'temperature': 0,
        'response_format': {'type': 'json_object'},
    }
    req = urllib.request.Request(
        url, data=json.dumps(payload).encode('utf-8'),
        headers={'Authorization': 'Bearer ' + cfg['api_key'],
                 'Content-Type': 'application/json'})
    # 429 限流 / 5xx 瞬时错误：指数退避重试（v0.28.4）。
    # 避免瞬时限流把整轮兜底打成 0/20 假阴性（实测 AMD 端点短爆发即 429）。
    # 400（模型不存在/鉴权失败）属硬错，立即降级，不重试。
    _退避 = [8, 16, 32, 48, 72]
    import llm_throttle  # 全局节流：validate→generate 两次调用须隔开，否则 AMD 端点 429
    for _尝试 in range(len(_退避) + 1):
        llm_throttle.限流(10)
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                data = json.loads(r.read().decode('utf-8'))
            content = data['choices'][0]['message']['content']
            return json.loads(content), data.get('usage', {})
        except urllib.error.HTTPError as e:
            if e.code == 429 or e.code >= 500:
                if _尝试 < len(_退避):
                    print('[兜底] LLM %d 限流/瞬时错，%.0fs 后重试(%d/%d)'
                          % (e.code, _退避[_尝试], _尝试 + 1, len(_退避)))
                    time.sleep(_退避[_尝试])
                    continue
            print('[兜底] LLM 调用失败，降级本地规则：%s' % e)
            return None, None
        except Exception as e:
            print('[兜底] LLM 调用失败，降级本地规则：%s' % e)
            return None, None
    print('[兜底] LLM 重试耗尽仍失败（需求=%s），兜底放弃' % 需求)
    return None, None


