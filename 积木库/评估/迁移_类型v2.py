def 迁移(写入=False):
    路径 = os.path.join(_库根, '索引.json')
    with open(路径, encoding='utf-8') as f:
        doc = json.load(f)
    块 = doc.get('块') or []

    改动, 漏标, 非法 = [], [], []
    for b in 块:
        名 = b.get('名称')
        if 名 not in 映射:
            漏标.append(名)
            continue
        入类, 出类 = 映射[名]
        ins = b.get('输入') or []
        if len(ins) != len(入类):
            非法.append('%s：映射入参 %d 个，索引里 %d 个' % (名, len(入类), len(ins)))
            continue
        for p, t in zip(ins, 入类):
            旧 = p.get('类型')
            if 旧 != t:
                改动.append('%-12s 输入 %-6s %s -> %s' % (名, p.get('名'), 旧, t))
                p['类型'] = t
        out = b.get('输出')
        if isinstance(out, dict):
            旧 = out.get('类型')
            if 旧 != 出类:
                改动.append('%-12s 输出        %s -> %s' % (名, 旧, 出类))
                out['类型'] = 出类

    for b in 块:
        for 问题 in T.校验契约(b):
            非法.append('%s：%s' % (b.get('名称'), 问题))

    print('── 类型 v2 迁移%s ──' % ('（写入）' if 写入 else '（预演）'))
    print('块总数 %d，映射覆盖 %d，改动 %d 处' % (len(块), len(块) - len(漏标), len(改动)))
    for x in 改动:
        print('  ' + x)
    if 漏标:
        print('\n[漏标] 以下块不在映射表中，类型未升级：')
        for x in 漏标:
            print('  ' + str(x))
    if 非法:
        print('\n[非法] 类型标注有问题：')
        for x in 非法:
            print('  ' + x)
        return 2

    if 写入:
        with open(路径, 'w', encoding='utf-8') as f:
            json.dump(doc, f, ensure_ascii=False, indent=2)
            f.write('\n')
        print('\n已写入 ' + 路径)
    else:
        print('\n（预演，未落盘；加 --写入 生效）')
    return 0


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--写入', action='store_true')
    a = p.parse_args()
    raise SystemExit(迁移(写入=a.写入))
