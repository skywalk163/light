def test_d0d1():
    """D0 关键词选块 + D1 Tfidf 补充"""
    from 选块 import select_blocks as 关键词选块, load_index
    from _ml_selector import 补充_选块, 分类_需求领域

    idx = load_index()
    全部 = idx.get('块', [])
    print('\n' + '=' * 70)
    print('D0+D1: 关键词选块 + Tfidf 补充测试')
    print('=' * 70)

    结果 = {'通过': 0, '失败': 0, '用例': len(_D0D1_CASES), '详情': []}
    top1_命中 = 0
    top3_命中 = 0
    总耗时 = 0.0

    for 需求, 期望块, 期望领域 in _D0D1_CASES:
        t0 = time.perf_counter()

        # D0 关键词选块
        候选 = 关键词选块(需求, idx, top=5)
        if 候选 and 候选[0].get('分数', 0) < 5.0:
            # D1 补充
            候选 = 补充_选块(需求, 候选, top=5)

        t = (time.perf_counter() - t0) * 1000
        总耗时 += t

        top1 = 候选[0]['名称'] if 候选 else '无'
        top3_names = [c['名称'] for c in 候选[:3]] if 候选 else []
        top1_ok = 期望块 in top1 or 期望块 in top3_names[:1]
        top3_ok = 期望块 in top3_names

        if top1_ok:
            top1_命中 += 1
        if top3_ok:
            top3_命中 += 1

        status = '✓' if top3_ok else '✗'
        结果['详情'].append({
            '需求': 需求, '期望块': 期望块, '期望领域': 期望领域,
            'Top-1': top1, 'Top-3': top3_names, '通过': top3_ok,
            '耗时ms': round(t, 2),
        })

        if top3_ok:
            结果['通过'] += 1
        else:
            结果['失败'] += 1
            print(f'  ✗ {需求:20s} 期望={期望块:10s} Top-1={top1:10s} Top-3={top3_names}')

    avg_ms = 总耗时 / len(_D0D1_CASES)
    结果['Top-1准确率'] = f'{top1_命中}/{len(_D0D1_CASES)} ({top1_命中/len(_D0D1_CASES)*100:.1f}%)'
    结果['Top-3准确率'] = f'{top3_命中}/{len(_D0D1_CASES)} ({top3_命中/len(_D0D1_CASES)*100:.1f}%)'
