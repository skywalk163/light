def _渲染(记录):
    """渲染一个块：返回 (文件名, 文件内容)。"""
    名称, 领域, 导出名, 描述, 输入, 输出, 模块, 符号, 参数, 函数体, 样例 = 记录
    lines = ['# 积木：%s（%s领域 L0）' % (名称, 领域),
             '# 契约：' + 描述]
    if 函数体 is None:
        # 直连 stdlib
        lines.append('从《%s》导入《%s》' % (模块, 符号))
        lines.append('导出 %s' % 导出名)
        lines.append('段落 %s 接收 %s：' % (导出名, '，'.join(n for n, _ in 输入)))
        lines.append('    返回 %s(%s)' % (符号, 参数))
    else:
        if 模块:
            lines.append('从《%s》导入《%s》' % (模块, 符号))
        lines.append('导出 %s' % 导出名)
        lines.append('段落 %s 接收 %s：' % (导出名, '，'.join(n for n, _ in 输入)))
        for ln in 函数体.split('\n'):
            lines.append(ln)
    return 名称, '\n'.join(lines) + '\n'


def _域目录(领域):
    return os.path.join(LIB, 领域)


def main():
    idx = json.load(open(IDX, encoding='utf-8'))
    现有 = {b['名称'] for b in idx['块']}
    现有导出 = {b['导出名'] for b in idx['块'] if b.get('导出名')}

    # 前缀冲突检查（现有 + 新块）
    全部导出 = list(现有导出) + [r[2] for r in _块]
    for i, a in enumerate(全部导出):
        for b in 全部导出[i + 1:]:
            if a != b and (b.startswith(a) or a.startswith(b)):
                print('!! 导出名前缀冲突：%s 与 %s' % (a, b))
                raise SystemExit(1)

    新增 = []
    for 记录 in _块:
        名称 = 记录[0]
        if 名称 in 现有:
            print('跳过（已有）：', 名称)
            continue
        领域 = 记录[1]
        os.makedirs(_域目录(领域), exist_ok=True)
        名, 内容 = _渲染(记录)
        with open(os.path.join(_域目录(领域), 名 + '.duan'), 'w', encoding='utf-8') as f:
            f.write(内容)
        _, _, 导出名, 描述, 输入, 输出, *_rest = 记录
        样例 = _rest[-1] if _rest else None
        idx['块'].append({
            '名称': 名, '领域': 领域, '层级': 0, '描述': 描述,
            '输入': [{'名': n, '类型': t} for n, t in 输入],
            '输出': {'类型': 输出},
            '稳定性': 'stable', '路径': '%s/%s.duan' % (领域, 名),
            '导出名': 导出名, '样例': 样例,
        })
        新增.append(名)
    with open(IDX, 'w', encoding='utf-8') as f:
        json.dump(idx, f, ensure_ascii=False, indent=2)
    print('新增 %d 块：%s' % (len(新增), '、'.join(新增)))
    print('总块数：%d' % len(idx['块']))


if __name__ == '__main__':
    main()
