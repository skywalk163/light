# -*- coding: utf-8 -*-
"""基准套件 v0.20 升级（一次性脚本）：

1. M3 扩库后，原先标 `应兜底` 的 10 条能力已经入库，改成指定期望块；
2. 为第二批 26 个新块补 19 条基准条目（P 系列）。

保留 5 条真·库外条目（拼音 / 繁简 / 正则 / base64 / 读本地文件），
兜底判定这项指标才有观测对象。
"""
import io
import json
import os

_HERE = os.path.abspath(os.path.dirname(__file__))
_P = os.path.join(_HERE, '评估', '基准.json')

# 原「库外」→ 现「库内」：id -> (期望块, 新标签)
转入库 = {
    'X03': (['时间格式'], ['日期']),
    'X04': (['JSON解析'], ['格式']),
    'X07': (['身份证'], ['校验']),
    'X08': (['天数差'], ['日期']),
    'X10': (['标准差'], ['数据']),
    'X11': (['前缀和'], ['数据']),
    'X12': (['取绝对'], ['工具']),
    'X13': (['地址转数'], ['网络']),
    'X14': (['随机标识'], ['工具']),
    'X15': (['文本相似'], ['文本']),
}

新条目 = [
    dict(id='P01', 需求='找出这组数据里出现次数最多的值', 期望块=['众数'],
         输入='[1, 2, 2, 3]', 标签=['数据']),
    dict(id='P02', 需求='把这批数归一化到 0 到 1 之间', 期望块=['归一化'],
         输入='[1, 2, 3]', 标签=['数据']),
    dict(id='P03', 需求='求这组数据的 90 分位数', 期望块=['百分位'],
         输入='[1, 2, 3, 4]', 标签=['数据']),
    dict(id='P04', 需求='求 12 和 18 的最大公约数', 期望块=['最大公约'],
         输入='12', 标签=['工具']),
    dict(id='P05', 需求='算一下这两个数的最小公倍数', 期望块=['最小公倍'],
         输入='4', 标签=['工具']),
    dict(id='P06', 需求='把这个数限幅在上下界之间', 期望块=['数值限幅'],
         输入='15', 标签=['工具']),
    dict(id='P07', 需求='把这段 CSV 文本拆成二维表格', 期望块=['CSV解析'],
         输入='"a,1"', 标签=['格式']),
    dict(id='P08', 需求='把 a=1;b=2 这样的键值串解析成表', 期望块=['键值解析'],
         输入='"a=1;b=2"', 标签=['格式']),
    dict(id='P09', 需求='把这个对象序列化成 JSON 文本', 期望块=['JSON文本'],
         输入='[1, 2]', 标签=['格式']),
    dict(id='P10', 需求='把整数还原成 IP 地址', 期望块=['数转地址'],
         输入='16909060', 标签=['网络']),
    dict(id='P11', 需求='从这条链接里取出域名', 期望块=['域名提取'],
         输入='"https://a.example.com/p"', 标签=['网络']),
    dict(id='P12', 需求='计算两段文本的编辑距离', 期望块=['编辑距离'],
         输入='"kitten"', 标签=['文本']),
    dict(id='P13', 需求='把每个单词的首字母改成大写', 期望块=['词首大写'],
         输入='"hello world"', 标签=['文本']),
    dict(id='P14', 需求='在前面补零凑够三位宽度', 期望块=['左侧补零'],
         输入='"7"', 标签=['文本']),
    dict(id='P15', 需求='检查这个网址格式对不对', 期望块=['网址合法'],
         输入='"https://a.com"', 标签=['校验']),
    dict(id='P16', 需求='判断这个年月日是不是真实存在的日期', 期望块=['日期合法'],
         输入='2023', 标签=['日期']),
    dict(id='P17', 需求='数一数这段话里有多少个汉字', 期望块=['汉字计数'],
         输入='"你好abc"', 标签=['中文']),
    dict(id='P18', 需求='按复利算这笔本金几年后的终值', 期望块=['复利终值'],
         输入='1000', 标签=['财务']),
    dict(id='P19', 需求='这笔房贷等额本息每月要还多少钱', 期望块=['等额本息'],
         输入='10000', 标签=['财务']),
]


def main():
    d = json.load(io.open(_P, encoding='utf-8'))
    d['版本'] = 'v0.20'
    改 = 0
    for e in d['条目']:
        if e['id'] in 转入库:
            期望, 标签 = 转入库[e['id']]
            e['期望块'] = 期望
            e.pop('应兜底', None)
            e['标签'] = 标签
            改 += 1
    有 = {e['id'] for e in d['条目']}
    加 = 0
    for n in 新条目:
        if n['id'] in 有:
            continue
        d['条目'].append(n)
        加 += 1
    io.open(_P, 'w', encoding='utf-8').write(
        json.dumps(d, ensure_ascii=False, indent=2) + '\n')
    库外 = [e['id'] for e in d['条目'] if e.get('应兜底')]
    print('转入库 %d 条，新增 %d 条，现共 %d 条；剩余库外 %d 条 %s'
          % (改, 加, len(d['条目']), len(库外), 库外))


if __name__ == '__main__':
    main()
