def _是通用_各元素块(名称, 领域):
    """判断是否是跨域重复的各元素块"""
    if 领域 == '数据':
        return False
    # 检查是否以"各元素"开头
    if 名称 in _通用_各元素块:
        return True
    if 名称 in _通用_各元素_后缀:
        return True
    # 检查带领域后缀的
    for 后缀名 in list(_通用_各元素块):
        if 名称 == 后缀名 or 名称.endswith(领域):
            base = 名称.replace(领域, '') if 名称.endswith(领域) else 名称
            if base in _通用_各元素块:
                return True
    return False


def _是通用_成对块(名称, 领域):
    if 领域 == '数据':
        return False
    return 名称 in _通用_成对块 or 名称.startswith('成对')


def _是通用_滚动块(名称, 领域):
    if 领域 == '数据':
        return False
    return 名称 in _通用_滚动块 or 名称.startswith('滚动')


def _是通用_过滤块(名称, 领域):
    if 领域 == '数据' or 领域 == '集合':
        return False
    return 名称 in _通用_过滤块 or 名称.startswith('过滤')


def _是通用_乘积块(名称, 领域):
    """乘积{领域}块只在数学领域有意义"""
    if 领域 == '数学':
        return False
    return 名称.startswith('乘积')


def _是通用_补充分配(名称, 领域):
    """补充块通常在各领域尾部重复"""
    if 领域 == '数据':
        return False
    # 检查是否包含"环境"后缀
    if 名称.endswith('环境'):
        return True
    return False


def 是通用块(块):
    """判断块是否是跨域重复的通用块"""
    名称 = 块['名称']
    领域 = 块['领域']
    return (
        _是通用_各元素块(名称, 领域) or
        _是通用_成对块(名称, 领域) or
        _是通用_滚动块(名称, 领域) or
        _是通用_过滤块(名称, 领域) or
        _是通用_乘积块(名称, 领域) or
        _是通用_补充分配(名称, 领域)
    )


