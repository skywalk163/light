def _提取参数(变换):
    """从变换表达式自动提取参数名（排除运算符、关键字、方法名）"""
    import re
    # 去掉字符串字面量，避免将 '非空' 等误识别为参数
    变换 = re.sub(r"'[^']*'", '', 变换)
    变换 = re.sub(r'"[^"]*"', '', 变换)
    ids = re.findall(r'[a-zA-Z_\u4e00-\u9fff][a-zA-Z0-9_\u4e00-\u9fff]*', 变换)
    
    # 方法名（点号后的标识符）
    方法名 = set()
    for m in re.finditer(r'\.([a-zA-Z_\u4e00-\u9fff][a-zA-Z0-9_\u4e00-\u9fff]*)', 变换):
        方法名.add(m.group(1))
    
    # 排除运算符和关键字
    排除 = {
        '加', '减', '乘', '除', '模', '幂', '加上', '减去', '乘以', '除以', '模以', '幂以',
        '大于', '小于', '等于', '不等于', '大于等于', '小于等于', '不小于', '不大于',
        '与', '或', '非', '且', '在', '不', '为', '包含', '属于', '不在',
        '如果', '则', '否则', '那么', '否则若', '若', '的', '长度', '整数', '真', '假', '空',
        '返回', '设', '当', '遍历', '每', '结果', 'i', '数', '逻辑',
        '跳过', '跳出', '结束', '等待', '新建', '函数', '段落', '接收', '导出', '导入',
        '父', '己', '自', '步', '至', '到',
        '旧', '新', '值', '模式', '子', '起', '止', '分隔',
        '和', '同', '跟', '及', '或', '亦', '也', '来', '去', '以', '由', '将', '把', '被',
    }
    
    参数 = []
    for id in ids:
        if id not in 排除 and id not in 方法名 and id not in 参数:
            if not id.isdigit():
                参数.append(id)
    
    return ','.join(参数) if 参数 else '输入'


