def _哈希_文件名(名称):
    """用名称的哈希取前 8 位作为文件名后缀，避免重复"""
    h = hashlib.md5(名称.encode('utf-8')).hexdigest()[:8]
    return h


def 生成_所有块():
    """生成所有积木，返回 (块列表, 索引条目列表)"""
    所有块 = []
    for 生成函数 in 生成函数们:
        所有块.extend(生成函数())
    return 所有块


def 写入_文件(块列表):
    """为每个块写入 .light 文件，并返回索引条目"""
    索引条目 = []
    os.makedirs(os.path.join(_HERE, '生成'), exist_ok=True)

    for b in 块列表:
        名称 = b['名称']
        领域 = b['领域']
        领域目录 = os.path.join(_HERE, 领域)
        os.makedirs(领域目录, exist_ok=True)

        # 文件名：用名称 + 哈希避免重复
        h = _哈希_文件名(名称)
        路径 = os.path.join(领域, f'{名称}.light')
        # 如果路径已存在，用哈希后缀
        最终路径 = 路径
        完整路径 = os.path.join(_HERE, 最终路径)
        if os.path.exists(完整路径):
            最终路径 = os.path.join(领域, f'{名称}_{h}.light')
            完整路径 = os.path.join(_HERE, 最终路径)

        # 写入文件
        with open(完整路径, 'w', encoding='utf-8') as f:
            f.write(b['源码'])

        # 构建索引条目
        条目 = {
            '名称': 名称,
            '领域': 领域,
            '层级': b.get('层级', 0),
            '描述': b['描述'],
            '输入': b.get('输入', []),
            '输出': b.get('输出', {}),
            '稳定性': b.get('稳定性', 'generated'),
            '路径': 最终路径,
            '导出名': b.get('导出名', 名称),
        }
        索引条目.append(条目)

    return 索引条目


def 更新_索引(新条目):
    """合并新条目到索引.json"""
    索引路径 = os.path.join(_HERE, '索引.json')
    with open(索引路径, 'r', encoding='utf-8') as f:
        索引 = json.load(f)

    现有名称 = set(b['名称'] for b in 索引['块'])
    新增 = 0
    for 条目 in 新条目:
        if 条目['名称'] not in 现有名称:
            索引['块'].append(条目)
            现有名称.add(条目['名称'])
            新增 += 1

    索引['版本'] = '0.2.0'
    索引['生成时间'] = '2026-08-10'
    索引['块总数'] = len(索引['块'])

    with open(索引路径, 'w', encoding='utf-8') as f:
        json.dump(索引, f, ensure_ascii=False, indent=2)

    return 新增


