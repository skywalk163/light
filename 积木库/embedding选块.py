_缓存 = {}


def 可选块(blocks):
    """滤掉『选块可见=false』的块。

    自动织出来的「聚合_*」是组合脚手架，不是一项能力：它的概念集是若干精确块的并集，
    会稳定压过被它包含的那一个（跑分 C04：聚合_中文_数_3项 0.928 盖过 中文数字 0.916）。
    组合装配要的是「刚好够用」，不是「顺带全算一遍」。
    """
    return [b for b in blocks if b.get('选块可见', True)]


class _索引:
    def __init__(self, blocks):
        self.blocks = blocks
        self.vecs = [_块概念向量(b) for b in blocks]


def _get(索引):
    key = id(索引)
    if key not in _缓存:
        _缓存[key] = _索引(可选块(索引.get('块') or []))
    return _缓存[key]


def _to_candidate(b, score):
    d = b.get('领域') or []
    d0 = d[0] if isinstance(d, list) and d else (d if isinstance(d, str) else '?')
    return {
        '名称': b.get('名称'), '领域': d0, '导出名': b.get('导出名', '?'),
        '路径': b.get('路径', ''), '描述': b.get('描述', ''),
        '分数': round(score, 4),
    }


def embedding_select(需求, index, top=None, real=None):
    """语义选块：返回候选列表（与 select_blocks 同构，含 分数）。

    - 默认：概念图向量（零依赖）。库外概念→余弦≈0→空候选→上层兜底。
    - 若装了 sentence_transformers（且 real 不为 False），自动改用真·句向量做更细召回。
    - real=True 时强制走真向量（不可用则报错提示）。
    """
    blocks = 可选块(index.get('块') or [])
    if not blocks:
        return []

    # v0.17：默认不再自动启用真向量。基准跑分（评估/跑分.py，62 条）显示在本库规模下
    # 概念图 0.984 链路正确率 / 0.1ms，而 text2vec 真向量仅 0.823 / 3700ms——短查询与
    # 长描述的句向量相似度趋同（各向异性），反而把「求和/最大/计数」冲散到统计块上。
    # 因此真向量降级为显式实验选项：--real 或 DUAN_EMBED_REAL=1。
    if real is None:
        real = True if os.environ.get('DUAN_EMBED_REAL') == '1' else None
    use_real = bool(real)
    if use_real:
        try:
            return _真向量检索(需求, blocks, top or 5)
        except Exception as e:
            if real is True:
                raise
            print('[embedding] 真向量检索失败，降级概念图：%s' % e)

    idx = _get(index)
    q = 概念向量(需求)
    # 查询侧各概念命中别名的最长长度（具体度），仅用于「余弦平局」决胜，
    # 不改变全局排序——避免 v0.22 早期「具体度加权」拖累主基准（库外召回掉到0.6）。
    q_spans = _扫描概念带位置(需求)
    q_spec = {c: max(e - s for s, e in sp) for c, sp in q_spans.items()}
    scored = []
    for b, vec in zip(idx.blocks, idx.vecs):
        # 能力边界约束：只共享通用领域概念（如都带『文本』）不算命中。
        # 「base64 编码」与「转小写」同属文本域，但能力完全不同——此约束让这类
        # 需求直接得到空候选，从而正确走兜底，而不是硬塞一个同域块。
        shared = (set(q) & set(vec)) - _通用领域
        if not shared:
            continue
        s = _余弦(q, vec)
        if s >= EMBED_FLOOR:
            # v0.22+ 复合块覆盖度（门控版）：查询显式表达「要一份同时含多指标的复合结果」
            # （带 同时/都/两个/一并/一起/以及/各自/各项/多项/既…又 等复合意图标记，且点名
            # ≥2 个具体概念）时，只满足部分概念的块（如 范围跨度 只含极差）按比例降权，让复合块
            # （统计双指标=均值+极差）胜出。顺序型需求（算完X再看看Y、先X后Y）不带复合标记，
            # 不触发，避免把「描述统计」误推到「算均值再看方差」这类两步操作上（S07 教训）。
            # 单概念查询恒不触发（所有命中块 covered=1.0，乘数恒 1，排序不变）。
            q_specific = set(q) - _通用领域
            复合意图 = any(m in 需求 for m in
                         ('同时', '都', '这两个', '那两个', '两者', '一并', '一起',
                          '以及', '各自', '各项', '多项', '既', '又', '全都要'))
            if len(q_specific) > 1 and 复合意图:
                s = s * (len(shared) / len(q_specific))
            spec = max((q_spec.get(c, 0) for c in shared), default=0)
            scored.append((s, spec, b))
    scored.sort(key=lambda x: (-x[0], -x[1]))
    if not scored:
        return []
    候选 = [_to_candidate(b, s) for s, spec, b in scored]
    return 候选[:top] if top else 候选


def _cli(argv=None):
    p = argparse.ArgumentParser(
        description='段言积木 embedding 选块 v0.16（概念图 / 真·句向量）')
    p.add_argument('需求', help='自然语言需求文本')
    p.add_argument('--top', type=int, default=5, help='候选数上限')
    p.add_argument('--real', action='store_true',
                   help='强制走真·句向量（需 sentence_transformers）')
    args = p.parse_args(argv)

    index = load_index()
    if args.real and not _真向量可用():
        print('[embedding] 未安装 sentence_transformers，无法使用 --real')
        return 1
    mode = '真·句向量' if (args.real or _真向量可用()) else '概念图向量'
    候选 = embedding_select(args.需求, index, top=args.top,
                          real=(True if args.real else None))
    print(json.dumps({'需求': args.需求, '模式': mode,
                      '块总数': len(index.get('块') or []),
                      '候选': 候选 if 候选 else '（空：需求未命中任何库内概念）'},
                     ensure_ascii=False, indent=2))
    return 0


