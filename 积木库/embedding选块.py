# ---------------------------------------------------------------------------
# v0.18：从属子句降权（句法特征）
#
# 中文需求常把「怎么做」写在前面、「要什么」写在后面：
#     「排序后处在中间位置的那个值」  ← 排序是定义方式，中位数才是目标
#     「求和再算平均」                ← 求和是前置步骤，平均才是落点
# v0.17 之前两个概念同权，`排序列表` 与 `中位数` 余弦完全相同（0.686 打平），
# top1 随索引顺序抖动 —— 这就是基准里最后一条失败项 D13。
#
# 修法：命中片段紧跟从属标记（后/之后/然后/再/完…）或被「先」引导时，判定为
# 「前置步骤」，权重 ×0.6。余弦对整体缩放不敏感，所以**单概念查询完全不受影响**，
# 只有多概念查询才会被重新排序——这正是我们要的最小扰动。
# ---------------------------------------------------------------------------
_从属后标记 = ('完成之后', '完成后', '完之后', '好之后', '之后', '然后',
               '以后', '过后', '完后', '好后', '后再', '后', '完', '再')
_从属前标记 = ('首先', '先')
_W从属 = 0.6


def _是从属(text, s, e):
    """命中片段 text[s:e] 是否处于「前置步骤」位置。"""
    尾 = text[e:]
    if any(尾.startswith(m) for m in _从属后标记):
        return True
    头 = text[:s]
    return any(头.endswith(m) for m in _从属前标记)


