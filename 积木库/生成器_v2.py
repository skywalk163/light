def 验证_光明语法(源码):
    """检查光明语言语法，返回错误列表（空列表=通过）"""
    errors = []
    lines =源码.split('\n')

    # 检查是否有内容
    if not 源码.strip():
        errors.append('源码为空')
        return errors

    # 检查导出行
    导出行 = None
    段落行 = None
    导出名 = None
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith('导出 '):
            if 导出行 is not None:
                errors.append(f'第{i+1}行：重复的导出声明')
            else:
                导出行 = i
                导出名 = stripped[3:].strip()
        if stripped.startswith('段落 '):
            if 段落行 is not None:
                errors.append(f'第{i+1}行：重复的段落声明')
            else:
                段落行 = i

    if 导出行 is None:
        errors.append('缺少导出声明')
    if 段落行 is None:
        errors.append('缺少段落声明')

    # 检查导出名和段落名一致
    if 导出名 and 段落行 is not None:
        段落内容 = lines[段落行].strip()
        # 段落名 = 导出名 接收 ...
        parts = 段落内容[3:].split('接收')
        if parts:
            段落名 = parts[0].strip()
            if 段落名 != 导出名:
                errors.append(f'导出名"{导出名}"与段落名"{段落名}"不一致')

    # 检查缩进
    in_loop = False
    in_if = False
    has_else = False
    for i, line in enumerate(lines):
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith('#'):
            continue
        if stripped.startswith('导出') or stripped.startswith('段落'):
            continue

        # 代码行必须有缩进
        if not line.startswith('    '):
            if stripped not in ('',):
                errors.append(f'第{i+1}行：缺少缩进')

        # 检查当循环
        if stripped.startswith('当 '):
            in_loop = True
        if stripped.startswith('如果 '):
            in_if = True
            has_else = False
        if stripped.startswith('否则'):
            has_else = True
            # 如果前面没有如果，错误
            if not in_if:
                errors.append(f'第{i+1}行：否则没有对应的如果')

    # 检查如果/否则配对（允许如果多于否则，但不允许否则没有如果）
    if_count = 0
    else_count = 0
    for line in lines:
        s = line.strip()
        if s.startswith('如果 '):
            if_count += 1
        if s == '否则：':
            else_count += 1
    if else_count > if_count:
        errors.append(f'否则({else_count})多于如果({if_count})，存在多余的否则')

    # 检查常见的表达式错误：缺少运算符
    for i, line in enumerate(lines):
        s = line.strip()
        # 检查"结果 列表[i]"模式（缺少运算符）
        import re
        m = re.search(r'设\s+结果\s+为\s+结果\s+列表\[i\]\s+', s)
        if m and not re.search(r'设\s+结果\s+为\s+结果\s+(加|减|乘|除|模)\s+', s):
            # 如果后面接的是加/减/乘/除，是OK的
            # 检查是否是"结果 列表[i] 加 列表[i]"这种模式
            if not re.search(r'设\s+结果\s+为\s+结果\s+(加|减|乘|除|模)\s+', s):
                errors.append(f'第{i+1}行：可能缺少运算符')

    return errors


