def 添加前缀(条目列表, 领域名):
    """为每个条目的导出名添加领域前缀"""
    新列表 = []
    for 条目 in 条目列表:
        新条目 = list(条目)
        # 导出名是第二个元素（索引1）
        if len(新条目) >= 2:
            新条目[1] = f'{新条目[1]}{领域名}'
        新列表.append(新条目)
    return 新列表

