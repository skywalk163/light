def 生成单体补充(领域名, 条目列表):
    """生成补充单体块列表"""
    代码 = f"\n    # 补充{领域名}操作\n    补充{领域名}_单体 = [\n"
    for 名称, 导出名, 描述, 输入类型, 输出类型, 变换 in 条目列表:
        代码 += f"        ('{名称}', '{导出名}', '{描述}', '{输入类型}', '{输出类型}', '{变换}'),\n"
    代码 += "    ]\n"
    代码 += f"    for 名称, 导出名, 描述, 输入类型, 输出类型, 变换 in 补充{领域名}_单体:\n"
    代码 += f"        块.append(_单体('{领域名}', 名称, 导出名, 描述, 输入类型, 输出类型, 变换))\n\n"
    return 代码

