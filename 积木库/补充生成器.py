def 生成通用映射(领域名, 条目):
    """生成通用映射补充 - 导出名包含领域前缀以避免去重"""
    code = f"\n    # 补充{领域名}映射操作\n    补充{领域名}_映射 = [\n"
    for item in 条目:
        名称, 导出名, 描述, 映射操作 = item
        唯一导出名 = f'{导出名}{领域名}'
        code += f"        ('{名称}', '{唯一导出名}', '{描述}', '{映射操作}'),\n"
    code += "    ]\n"
    code += f"    for 名称, 导出名, 描述, 映射操作 in 补充{领域名}_映射:\n"
    code += f"        块.append(_映射('{领域名}', 名称, 导出名, 描述, 映射操作))\n\n"
    return code

