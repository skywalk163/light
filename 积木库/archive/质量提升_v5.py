def 是真正低质量块(块):
    """判断是否真正低质量：纯恒等(返回 输入) 或 纯常量(返回 数字)"""
    源码 = 块.get('源码', '')
    for line in 源码.split('\n'):
        line = line.strip()
        if line.startswith('返回'):
            content = line.replace('返回 ', '').strip()
            # 纯恒等
            if content == '输入':
                return True
            # 纯常量
            try:
                float(content)
                return True
            except ValueError:
                pass
    return False


def 去重合并(现有块, 新块字典):
    导出名映射 = {}
    for 块 in 现有块:
        导出名映射[块['导出名']] = 块
    
    新增计数 = 0
    替换计数 = 0
    for 领域, 块列表 in 新块字典.items():
        for 块 in 块列表:
            导出名 = 块['导出名']
            if 导出名 in 导出名映射:
                替换计数 += 1
            else:
                新增计数 += 1
            导出名映射[导出名] = 块
    
    合并后 = list(导出名映射.values())
    print(f'[合并] 现有 {len(现有块)} + 新增 {新增计数}（替换 {替换计数} 个）= 总计 {len(合并后)}')
    return 合并后


def 写入v4json(块列表):
    v4路径 = os.path.join(_HERE, '积木库_导出_v4.json')
    输出 = {
        '版本': '5.1',
        '领域数': len(set(块['领域'] for 块 in 块列表)),
        '总块数': len(块列表),
        '块': 块列表,
    }
    with open(v4路径, 'w', encoding='utf-8') as f:
        json.dump(输出, f, ensure_ascii=False, indent=2)
    print(f'[写入] {v4路径}: {len(块列表)} 个块')


def _安全文件名(名称):
    安全 = ''
    for c in 名称:
        if c in r'<>:"/\|?*':
            安全 += '_'
        else:
            安全 += c
    return 安全


def 写入单个文件(块列表):
    v5目录 = os.path.join(_HERE, 'blocks_v5')
    if os.path.exists(v5目录):
        shutil.rmtree(v5目录)
    os.makedirs(v5目录)
    写入计数 = 0
    领域目录 = {}
    for 块 in 块列表:
        领域 = 块['领域']
        领域路径 = os.path.join(v5目录, 领域)
        if 领域 not in 领域目录:
            os.makedirs(领域路径, exist_ok=True)
            领域目录[领域] = True
        导出名 = _安全文件名(块['导出名'])
        源码 = 块.get('源码', '')
        if 源码:
            文件路径 = os.path.join(领域路径, f'{导出名}.light')
            with open(文件路径, 'w', encoding='utf-8') as f:
                f.write(源码)
            写入计数 += 1
    print(f'[写入] blocks_v5/: {写入计数} 个 .light 文件')


def 打印统计(块列表):
    print()
    print('=' * 60)
    print(f'{"领域":<8} {"块数":<6} {"占比":<8}')
    print('-' * 60)
    领域计数 = {}
    for 块 in 块列表:
        领域 = 块['领域']
        领域计数[领域] = 领域计数.get(领域, 0) + 1
    总计 = len(块列表)
    for 领域 in sorted(领域计数.keys()):
        数量 = 领域计数[领域]
        占比 = 数量 / 总计 * 100
        print(f'{领域:<8} {数量:<6} {占比:>6.2f}%')
    print('-' * 60)
    print(f'{"总计":<8} {总计:<6} {"100.00%":<8}')
    print(f'{"领域数":<8} {len(领域计数):<6}')
    print('=' * 60)


