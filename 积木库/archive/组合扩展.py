def 批量_单体变体(领域, 基础名, 基础导出, 基础描述, 输入类型, 输出类型, 变换, 边界列表=None, 链式次数=None):
    """生成单输入变体：类型变体 × 边界变体 × 链式变体"""
    块 = []
    # 基础版本
    块.append(生成_单体(领域, 基础名, 基础导出, 基础描述, 输入类型, 输出类型, 变换))
    # 边界变体
    if 边界列表:
        for 边界名, 边界变换 in 边界列表:
            名 = f'{基础名}_{边界名}'
            导出 = f'{基础导出}_{边界名}'
            描述 = f'{基础描述}（{边界名}）'
            实际变换 = 边界变换.replace('{变换}', 变换)
            块.append(生成_单体(领域, 名, 导出, 描述, 输入类型, 输出类型, 实际变换))
    # 链式变体（连续应用）
    if 链式次数:
        for 次数 in 链式次数:
            if 次数 <= 1:
                continue
            名 = f'{基础名}_链式{次数}'
            导出 = f'{基础导出}_链式{次数}'
            描述 = f'{基础描述}（连续{次数}次）'
            链式变换 = '('.join([变换] * 次数) + ')' * (次数 - 1) if 次数 > 1 else 变换
            块.append(生成_单体(领域, 名, 导出, 描述, 输入类型, 输出类型, 链式变换))
    return 块

