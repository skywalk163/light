def 批量_系统组合爆炸(领域, 变体类型='数值'):
    """系统性组合爆炸生成——通过参数组合生成大量变体
    变体类型: '数值', '文本', '列表', '通用'
    """
    块 = []
    
    if 变体类型 in ('数值', '通用'):
        # 1. 数值变换 (50)
        for 名称, 导出名, 描述, 变换 in _数值变换:
            块.append(生成_单体(领域, 名称, 导出名, 描述, '数', '数', 变换))
        
        # 2. 二元运算 (5)
        for 名称, 导出, 操作 in _二元运算:
            块.append(生成_二体(领域, 名称, 导出, f'{名称}运算', '数', '数', 操作))
            # 三元变体
            块.append(生成_三体(领域, f'{名称}_三元', f'{名称}_三元', f'{名称}运算（三元）', '数', '数', f'甲 {操作} 乙 {操作} 丙'))
            # 四元变体
            块.append(生成_四体(领域, f'{名称}_四元', f'{名称}_四元', f'{名称}运算（四元）', '数', '数', f'甲 {操作} 乙 {操作} 丙 {操作} 丁'))
            # 边界变体
            块.append(生成_二体(领域, f'{名称}_零安全', f'{名称}_零安全', f'{名称}运算（零安全）', '数', '数', f'如果 乙 等于 0 则 0 否则 甲 {操作} 乙'))
            块.append(生成_二体(领域, f'{名称}_上限', f'{名称}_上限', f'{名称}运算（上限1000）', '数', '数', f'如果 (甲 {操作} 乙) 大于 1000 则 1000 否则 甲 {操作} 乙'))
            块.append(生成_二体(领域, f'{名称}_下限', f'{名称}_下限', f'{名称}运算（下限0）', '数', '数', f'如果 (甲 {操作} 乙) 小于 0 则 0 否则 甲 {操作} 乙'))
        
        # 3. 三元运算 (15)
        for 名称, 导出, 变换 in _三元运算:
            块.append(生成_三体(领域, 名称, 导出, f'{名称}', '数', '数', 变换))
        
        # 4. 比较运算 (6)
        for 名称, 导出, 操作 in _比较运算:
            块.append(生成_二体(领域, 名称, 导出, f'{名称}比较', '数', '数', 操作))
        
        # 5. 复合运算 (40) — 根据变量名选择正确模板
        for 名称, 导出名, 描述, 变换 in _复合运算:
            if '丙' in 变换:
                块.append(生成_三体(领域, 名称, 导出名, 描述, '数', '数', 变换))
            elif '乙' in 变换:
                块.append(生成_二体(领域, 名称, 导出名, 描述, '数', '数', 变换))
            else:
                块.append(生成_单体(领域, 名称, 导出名, 描述, '数', '数', 变换))
        
        # 6. 条件运算 (30) — 根据变量名选择正确模板
        for 名称, 导出名, 描述, 变换 in _条件运算:
            if '甲' in 变换:
                块.append(生成_二体(领域, 名称, 导出名, 描述, '数', '数', 变换))
            else:
                块.append(生成_单体(领域, 名称, 导出名, 描述, '数', '数', 变换))
    
    if 变体类型 in ('文本', '通用'):
        # 7. 字符串操作 (50)
        for 名称, 导出名, 描述, 操作 in _字符串操作:
            块.append(生成_字符串(领域, 名称, 导出名, 描述, '文本', 操作))
        
        # 8. 类型转换 (20)
