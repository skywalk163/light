def 验证_光明语法(源码):
    errors = []
    lines = 源码.split('\n')
    if not 源码.strip():
        errors.append('源码为空')
        return errors
    导出行 = None
    段落行 = None
    导出名 = None
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith('导出 '):
            if 导出行 is not None:
                errors.append(f'第{i+1}行：重复的导出声明')
            else:
                导出行 = i
                导出名 = stripped[3:].strip()
        if stripped.startswith('段落 '):
            if 段落行 is not None:
                errors.append(f'第{i+1}行：重复的段落声明')
            else:
                段落行 = i
    if 导出行 is None:
        errors.append('缺少导出声明')
    if 段落行 is None:
        errors.append('缺少段落声明')
    if 导出名 and 段落行 is not None:
        段落内容 = lines[段落行].strip()
        parts = 段落内容[3:].split('接收')
        if parts:
            段落名 = parts[0].strip()
            if 段落名 != 导出名:
                errors.append(f'导出名"{导出名}"与段落名"{段落名}"不一致')
    for i, line in enumerate(lines):
        stripped = line.strip()
        if not stripped or stripped.startswith('#') or stripped.startswith('导出') or stripped.startswith('段落'):
            continue
        if not line.startswith('    '):
            errors.append(f'第{i+1}行：缺少缩进')
    return errors


