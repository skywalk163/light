def _生成契约行(输入列表, 输出, 描述):
    """
    从块元数据生成契约行，确保契约与签名同源。
    输入列表: [{'名': '输入', '类型': '数'}, ...]
    输出: {'类型': '数'}
    描述: 字符串
    """
    输入类型列表 = [p['类型'] for p in 输入列表]
    输入类型串 = ', '.join(输入类型列表)
    输出类型 = 输出.get('类型', '空')
    if 描述:
        return f'# 契约：输入 [{输入类型串}] → 输出 {输出类型}（{描述}）'
    else:
        return f'# 契约：输入 [{输入类型串}] → 输出 {输出类型}'


def _注入契约行(源码, 契约行):
    """替换源码中的契约行为同源生成的契约行，禁止漂移"""
    lines = 源码.split('\n')
    new_lines = []
    已替换 = False
    for line in lines:
        if line.strip().startswith('# 契约：'):
            if not 已替换:
                new_lines.append(契约行)
                已替换 = True
        else:
            new_lines.append(line)
    if not 已替换:
        # 如果模板中没有契约行，在第一行注释后插入
        # 在 # 积木：... 行之后插入
        for i, line in enumerate(new_lines):
            if line.strip().startswith('# 积木：') and i + 1 < len(new_lines):
                new_lines.insert(i + 1, 契约行)
                break
    return '\n'.join(new_lines)


def _生成块(领域, 名称, 导出名, 描述, 输入, 输出, 源码):
    """生成块，自动注入同源契约行"""
    契约行 = _生成契约行(输入, 输出, 描述)
    源码 = _注入契约行(源码, 契约行)
    return {
        '名称': 名称, '领域': 领域, '层级': 0, '描述': 描述,
        '输入': 输入, '输出': 输出, '稳定性': 'generated', '导出名': 导出名, '源码': 源码,
    }


