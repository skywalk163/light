def _命中(候选, 期望):
    """检查候选列表中是否有任一期望块名"""
    候选名 = set(c['名称'] for c in 候选)
    for e in 期望:
        if e in 候选名:
            return True
    return False


def 运行基准(策略名, 策略函数, 测试集, index):
    """运行一组基准测试"""
    总 = len(测试集)
    命中 = 0
    耗时 = 0.0
    详细 = []

    for 用例 in 测试集:
        需求 = 用例[0]
        期望 = 用例[1]
        t0 = time.time()
        try:
            候选 = 策略函数(需求, index, top=3)
        except Exception as e:
            候选 = []
        t1 = time.time()
        耗时 += t1 - t0
        h = _命中(候选, 期望)
        if h:
            命中 += 1
        详细.append({
            '需求': 需求[:30],
            '期望': 期望[:3],
            '命中': h,
            '候选': [c['名称'] for c in 候选[:3]],
        })

    准确率 = 命中 / 总 * 100 if 总 > 0 else 0
    return {
        '策略': 策略名,
        '总用例': 总,
        '命中': 命中,
        '准确率': round(准确率, 1),
        '平均耗时': round(耗时 / 总 * 1000, 1),
        '详细': 详细,
    }


def 打印结果(结果):
    print(f"\n{'='*60}")
    print(f"  策略: {结果['策略']}")
    print(f"  准确率: {结果['命中']}/{结果['总用例']} ({结果['准确率']}%)")
    print(f"  平均耗时: {结果['平均耗时']}ms")
    print(f"{'='*60}")

    # 列出失败用例
    失败 = [d for d in 结果['详细'] if not d['命中']]
    if 失败:
        print(f"\n  失败用例 ({len(失败)}):")
        for d in 失败[:15]:
            print(f"    ✗ {d['需求']} → 期望: {d['期望']}, 实际: {d['候选']}")
        if len(失败) > 15:
            print(f"    ... 还有 {len(失败)-15} 个失败")


