    for info in all_infos:
        if not info['has_func'] or not info['func_name']:
            continue
        if not _is_self_recursive(info):
            continue
        if info['has_stub_marker']:
            stats['stub_already'] += 1
            continue
        
        if args.dry_run:
            print(f'  [干跑] 将标记: {info["rel_path"]}')
            stats['stub_marked'] += 1
        else:
            new_lines = _add_stub_marker(info['source_lines'])
            with open(info['path'], 'w', encoding='utf-8') as f:
                f.writelines(new_lines)
            stats['stub_marked'] += 1

    print(f'  已有标记: {stats["stub_already"]}')
    print(f'  新标记: {stats["stub_marked"]}')

    # ======== Fix3: 修正形参声明 ========
    # 策略：从body中提取所有token，找出未在形参中声明的变量名，补齐形参
    print('\n[Fix3] 修正形参声明与体内变量名一致...')
    
    # 应该被排除的token（不是变量的token）
    EXCLUDED_TOKENS = frozenset({
        '设', '为', '如果', '则', '否则', '当', '返回', '且', '或', '不',
        '真', '假', '加', '减', '乘', '除', '模', '小于', '大于', '等于',
        '长度', '结果', 'i', 'j', 'k', 'n', 'm',
        # 类型名（不是变量，是代码生成器映射问题）
        '文本', '列表', '字典', '集合', '字节', '逻辑', '日期', '时间',
        '整数', '浮点数', '字符串', '布尔', '小数', '数',
    })
    
    for info in all_infos:
        if not info['has_func'] or not info['func_name']:
            continue
        if info['has_stub_marker']:
            continue  # 跳过桩
        if _is_self_recursive(info):
            continue  # 跳过自递归桩
        
        func_name = info['func_name']
        params = info['params']
        body_text = info['body_text']
        if not body_text.strip():
            continue
        
        # 从body中提取所有token
        tokens = re.findall(r'[\w\u4e00-\u9fff]+', body_text)
        
        # 找出在body中引用但不在形参中的token
        undeclared = []
        seen = set()
        for token in tokens:
            if token.isdigit(): continue
            if token in seen: continue
            seen.add(token)
            if token in params: continue  # 已在形参中
            if token == func_name: continue  # 函数自身
            if token in EXCLUDED_TOKENS: continue  # 关键字/运算符
            if token in FUNC_LIKE_NAMES: continue  # 标准函数名
            # 检查是否可能是内置函数（在builtin_map中）
            try:
                import math, random
                if hasattr(math, token) or hasattr(random, token): continue
            except: pass
            undeclared.append(token)
        
        if not undeclared:
            continue
        
        # 将未声明变量加入形参
        old_params_str = ', '.join(params)
        # 用现有形参 + 未声明变量组成新形参
        # 保留原有形参顺序，将未声明变量按出现顺序追加
        existing_set = set(params)
        new_params = list(params)
        for v in undeclared:
            if v not in existing_set:
                new_params.append(v)
                existing_set.add(v)
        
        if new_params == params:
            continue
        
        new_params_str = ', '.join(new_params)
        if args.dry_run:
            print(f'  [干跑] 修正: {info["rel_path"]}  {old_params_str} → {new_params_str}')
            stats['param_decl_fixed'] += 1
        else:
            if _fix_param_declaration(info['source_lines'], old_params_str, new_params):
                with open(info['path'], 'w', encoding='utf-8') as f:
                    f.writelines(info['source_lines'])
                stats['param_decl_fixed'] += 1
                print(f'  修正: {info["rel_path"]}  {old_params_str} → {new_params_str}')

    print(f'  形参声明修正: {stats["param_decl_fixed"]}')

    # ======== Fix4: 修复常见语法错误 ========
    print('\n[Fix4] 修复常见语法错误...')
    for info in all_infos:
        if not info['has_func'] or not info['func_name']:
            continue
        if info['has_stub_marker']:
            continue
        
        body = info['body_lines']
        content = info['content']
        changed = False
        
        for line in body:
            # 修复双重操作符
            for pattern, replacement in [
                (r'乘 乘', '乘'),
                (r'加 加', '加'),
                (r'减 减', '减'),
                (r'除 除', '除'),
                (r'模 模', '模'),
            ]:
                if re.search(pattern, line):
                    new_content = content.replace(pattern, replacement)
                    if new_content != content:
                        if args.dry_run:
                            print(f'  [干跑] 语法修复: {info["rel_path"]}  {pattern} → {replacement}')
                            stats['syntax_fixed'] += 1
                        else:
                            content = new_content
                            changed = True
                            stats['syntax_fixed'] += 1
                            print(f'  语法修复: {info["rel_path"]}  {pattern} → {replacement}')
        
        if changed and not args.dry_run:
            with open(info['path'], 'w', encoding='utf-8') as f:
                f.write(content)

    print(f'  语法修复: {stats["syntax_fixed"]}')

    # ======== Fix5: 修复表达式中的无空格运算（如 i加1 → i 加 1） ========
    print('\n[Fix5] 修复表达式中的无空格运算...')
    # 模式：在标识符后直接跟运算符再接数字/标识符，如 i加1, i减1, 甲加乙
    # 仅在 body 中修复，不修改段落行（形参声明）
    EXPR_FIXES = [
        (r'i加1', 'i 加 1'),
        (r'i减1', 'i 减 1'),
        (r'i加2', 'i 加 2'),
        (r'i减2', 'i 减 2'),
        (r'j加1', 'j 加 1'),
        (r'j减1', 'j 减 1'),
        (r'k加1', 'k 加 1'),
        (r'k减1', 'k 减 1'),
        (r'n加1', 'n 加 1'),
        (r'n减1', 'n 减 1'),
    ]
    fix5_count = 0
    for info in all_infos:
        if not info['has_func'] or not info['func_name']:
            continue
        if info['has_stub_marker']:
            continue
        
        content = info['content']
        # 只在 body 中修复（缩进的行），不修复段落行
        changed = False
        for i, line in enumerate(info['source_lines']):
            if line.startswith('    ') or line.startswith('\t'):
                new_line = line
                for pattern, replacement in EXPR_FIXES:
                    new_line = re.sub(pattern, replacement, new_line)
                if new_line != line:
                    info['source_lines'][i] = new_line
                    changed = True
                    if not args.dry_run:
                        fix5_count += 1
        
        if changed and not args.dry_run:
            with open(info['path'], 'w', encoding='utf-8') as f:
                f.writelines(info['source_lines'])
    
    print(f'  表达式修复: {fix5_count}')

    # 总结
    print(f'\n{"="*60}')
    print(f'修复总结')
    print(f'{"="*60}')
    print(f'Fix2: 新标记自递归桩: {stats["stub_marked"]}')
    print(f'Fix3: 形参声明修正: {stats["param_decl_fixed"]}')
    print(f'Fix4: 语法修复: {stats["syntax_fixed"]}')
    print(f'Fix5: 表达式修复: {fix5_count}')
    
    if args.dry_run:
        print(f'\n[干跑模式] 未写入任何文件')
    else:
        print(f'\n[完成] 所有修复已写入文件')


