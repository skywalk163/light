def _parse_light_file(filepath):
    """解析 .light 文件"""
    with open(filepath, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    
    info = {
        'path': filepath,
        'rel_path': os.path.relpath(filepath, BLOCKS_DIR),
        'func_name': None,
        'params': [],
        'body_lines': [],
        'body_text': '',
        'has_export': False,
        'has_func': False,
        'has_stub_marker': False,
        'source_lines': lines,
        'content': ''.join(lines),
    }
    
    for line in lines:
        s = line.strip()
        # 导出行
        if s.startswith('导出 '):
            info['has_export'] = True
            info['export_name'] = s[3:].strip()
        # 段落行
        if s.startswith('段落 '):
            info['has_func'] = True
            m = re.match(r'段落\s+(\S+)\s+接收\s+(.+)', s)
            if m:
                info['func_name'] = m.group(1)
                params_str = m.group(2).strip()
                params_str = re.sub(r'[：:]$', '', params_str)
                info['params'] = [p.strip() for p in params_str.split(',')]
        # 体行
        if line.startswith('    ') or line.startswith('\t'):
            info['body_lines'].append(s)
            info['body_text'] += s + ' '
        # 状态标记
        if s.startswith('# 状态：') and '无实现' in s:
            info['has_stub_marker'] = True
    
    return info


def _get_body_vars(body_text, func_name):
    """从 body 中提取引用的变量名（排除函数名自身和标准函数）"""
    tokens = re.findall(r'[\w\u4e00-\u9fff]+', body_text)
    vars_used = set()
    for token in tokens:
        if token.isdigit():
            continue
        if token == func_name:
            continue
        if token in FUNC_LIKE_NAMES:
            continue
        if token in {'设', '为', '如果', '则', '否则', '当', '返回', '且', '或', '不',
                       '真', '假', '加', '减', '乘', '除', '模', '小于', '大于', '等于',
                       '长度', '结果', 'i', 'j', '输入', '文本', '列表', '甲', '乙', '丙',
                       '窗宽', '表甲', '表乙', '键', '窗口', '步长', '系数', '缩放因子',
                       '偏移量', '幂参数', '上界', '下界', '最小值', '最大值',
                       '均值', '标准差', '协方差', '方差', '均值甲', '均值乙',
                       '成本', '收入', '资产', '权益', '总资产', '流动负债', '存货'}:
            continue
        vars_used.add(token)
    return vars_used


def _is_self_recursive(info):
    """判断是否为自递归桩"""
    body = info['body_lines']
    if len(body) == 1 and body[0].startswith('返回 '):
        ret_val = body[0][3:].strip()
        m = re.match(r'^(\w[\w\u4e00-\u9fff]*)\(', ret_val)
        if m and m.group(1) == info['func_name']:
            return True
    return False


def _add_stub_marker(lines):
    """在文件头部添加状态标记"""
    insert_pos = 0
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith('#') and '契约' not in s:
            insert_pos = i + 1
        elif s.startswith('导出') or s.startswith('段落'):
            break
    status_line = '# 状态：签名占位，无实现\n'
    lines.insert(insert_pos, status_line)
    return lines


def _fix_param_declaration(lines, old_params, new_params):
    """修正形参声明"""
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith('段落 '):
            m = re.match(r'段落\s+(\S+)\s+接收\s+(.+)', s)
            if m:
                func_name = m.group(1)
                old_params_str = m.group(2).strip()
                old_params_str = re.sub(r'[：:]$', '', old_params_str)
                if old_params_str == old_params:
                    new_params_str = ', '.join(new_params)
                    lines[i] = f'段落 {func_name} 接收 {new_params_str}：\n'
                    return True
    return False


