_NEG = ['不', '否', '错', '误', '无关', '不能', '无法', '不对']


def _构造请求(需求, 候选, cfg):
    """构造发给 LLM 的请求（url, headers, payload）。dry-run 与真实调用共用。"""
    url = cfg['base_url'].rstrip('/') + '/chat/completions'
    cands = '\n'.join(
        '  - %s（领域=%s，输入=%s，输出=%s，描述=%s）' % (
            c.get('名称'), c.get('领域'),
            [p.get('类型') for p in (c.get('输入') or [])],
            (c.get('输出') or {}).get('类型'),
            c.get('描述', ''))
        for c in (候选 or [])[:5]) or '（无）'
    user = '需求：%s\n已选积木：\n%s\n请校验该组合是否满足需求。' % (需求, cands)
    payload = {
        'model': cfg['model'],
        'messages': [
            {'role': 'system', 'content': _SYSTEM},
            {'role': 'user', 'content': user},
        ],
        'temperature': 0,
        'response_format': {'type': 'json_object'},
    }
    return url, payload


def _llm_validate(需求, 候选, cfg):
    if not cfg.get('api_key'):
        return None
    url, payload = _构造请求(需求, 候选, cfg)
    req = urllib.request.Request(
        url, data=json.dumps(payload).encode('utf-8'),
        headers={'Authorization': 'Bearer ' + cfg['api_key'],
                 'Content-Type': 'application/json'})
    import llm_throttle  # 与兜底生成器共用同一节流器：跨 validate/generate 限速，消 429
    _退避 = [8, 16, 32, 48, 72]
    for _尝试 in range(len(_退避) + 1):
        llm_throttle.限流(10)
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                data = json.loads(r.read().decode('utf-8'))
            content = data['choices'][0]['message']['content']
            obj = json.loads(content)
            通过 = bool(obj.get('通过'))
            if isinstance(通过, str):
                通过 = 通过.strip().lower() not in _NEG
            return {'通过': 通过, '理由': str(obj.get('理由', ''))}
        except Exception as e:
            import time
            if _尝试 < len(_退避):
                print('[校验器] LLM 调用失败(%s)，%d秒后重试(%d/%d)' % (e, _退避[_尝试], _尝试 + 1, len(_退避)))
                time.sleep(_退避[_尝试])
            else:
                print('[校验器] LLM 调用失败，降级本地校验：%s' % e)
                return None
    return None


