#: 旧规则码 → L5xxx 诊断码（第 1 条 → L5004，依次顺排）。
LINT_RULE_MAP: Dict[str, str] = {
    rule_id: f"L{5004 + index}"
    for index, (rule_id, _severity, _message, _hint) in enumerate(_LINT_RULES)
}

#: lint 桥接码表条目（anchor 全部为 linter；码值 L5004-L5036）。
LINT_SPECS: Tuple[DiagnosticSpec, ...] = tuple(
    DiagnosticSpec(
        code=f"L{5004 + index}",
        severity=severity,
        message=message,
        hint=hint,
        anchor="linter",
        legacy=False,
    )
    for index, (rule_id, severity, message, hint) in enumerate(_LINT_RULES)
)

#: 首个 lint 桥接码（区间下界，供测试与文档引用）。
LINT_CODE_FIRST = "L5004"

#: 末个 lint 桥接码（区间上界，供测试与文档引用）。
LINT_CODE_LAST = f"L{5004 + len(_LINT_RULES) - 1}"


def lint_rule_to_code(rule_id: str) -> str:
    """旧 linter 规则码 → 新诊断码；未登记的旧码抛 ``KeyError``。

    反向查询（诊断码 → 旧规则码）用 ``{v: k for k, v in LINT_RULE_MAP.items()}``
    现场构建即可，码量小（≤ 40 条）不值得常驻第二张表。
    """
    return LINT_RULE_MAP[rule_id]
