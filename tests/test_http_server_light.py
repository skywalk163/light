# 判据 4：keep-alive 复用
# ===========================================================================
def test_keepalive复用():
    """同一连接连续两笔请求都得到响应；服务端记 2 笔（不是 1 笔也不是断连）。

    反跑点：把 处理连接 里的 keep-alive 循环（Connection: close 判定）改成
    「处理完一笔就跳出」，第二笔请求将无响应（读超时），本断言立红。
    """

    async def 主体(服务器, 端口):
        _, _, 读取器, 写入器 = await 发请求(端口, "GET", "/第一笔", 关闭=False)
        try:
            状态1, 体1 = await 复用发请求(读取器, 写入器, 端口, "GET", "/第二笔")
            assert 状态1 == 200
            assert 体1 == b"ok"
            assert 服务器.完成数 == 2
        finally:
            写入器.close()
            try:
                await 写入器.wait_closed()
            except Exception:
                pass

    跑服务端(快处理器, 主体)


