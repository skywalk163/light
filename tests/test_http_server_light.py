# 判据 5：客户端中途断开，服务端不崩
# ===========================================================================
def test_客户端中途断开服务端不崩():
    """连接后只发半截请求头就关闭：服务端记一笔错误，随后新请求仍 200。

    反跑点：把 读请求头 的「长(块) == 0 → 抛 连接中断」改成静默返回空头，
    服务端会把半截请求当合法请求处理，错误数记账断言立红。
    """

    async def 主体(服务器, 端口):
        读取器, 写入器 = await asyncio.open_connection("127.0.0.1", 端口)
        写入器.write("GET /半截 HTTP/1.1\r\nHost: x\r\n".encode("utf-8"))
        await 写入器.drain()
        写入器.close()
        try:
            await 写入器.wait_closed()
        except Exception:
            pass
        await asyncio.sleep(0.3)  # 等服务端读到 EOF 并记账
        assert 服务器.错误数 >= 1, "半截请求应被记账为一次连接中断"
        状态, _, _, _ = await 发请求(端口, "GET", "/断开后仍服务")
        assert 状态 == 200

    跑服务端(回显处理器, 主体)


