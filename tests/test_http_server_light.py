async def 读响应头(读取器):
    """读到 \r\n\r\n，返回整个头区块字节。"""
    缓冲 = b""
    while b"\r\n\r\n" not in 缓冲:
        块 = await 读取器.read(4096)
        if not 块:
            break
        缓冲 += 块
    return 缓冲


def 解析响应(头区块):
    """返回 [状态码, 头字典(小写键)]。"""
    行们 = 头区块.decode("utf-8", errors="replace").split("\r\n")
    状态 = int(行们[0].split()[1])
    头字典 = {}
    for 行 in 行们[1:]:
        if ":" in 行:
            名, 值 = 行.split(":", 1)
            头字典[名.strip().lower()] = 值.strip()
    return 状态, 头字典


async def 读响应(读取器):
    """读完整一笔响应（头+体），返回 [状态码, 体字节, 多余字节]。

    关键：小响应「头+体」常在同一次 read 里到达，必须先从头区块剥离体，
    不能把体交给 readexactly 再读（流里已空 → IncompleteReadError）。
    """
    缓冲 = b""
    while b"\r\n\r\n" not in 缓冲:
        块 = await 读取器.read(4096)
        if not 块:
            break
        缓冲 += 块
    分隔 = 缓冲.find(b"\r\n\r\n")
    头区块 = 缓冲[:分隔]
    剩余 = 缓冲[分隔 + 4:]
    状态, 头字典 = 解析响应(头区块)
    内容长度 = int(头字典.get("content-length", "0"))
    while len(剩余) < 内容长度:
        块 = await 读取器.read(4096)
        if not 块:
            break
        剩余 += 块
    return 状态, 剩余[:内容长度], 剩余[内容长度:]


async def 发请求(端口, 方法="GET", 路径="/", 头=None, 体=None, 关闭=True):
    """发一笔请求，返回 [状态码, 响应体字节, 读取器, 写入器]。"""
    读取器, 写入器 = await asyncio.open_connection("127.0.0.1", 端口)
    请求 = (方法 + " " + 路径 + " HTTP/1.1\r\nHost: 127.0.0.1\r\n").encode("utf-8")
    for 名, 值 in (头 or {}).items():
        请求 += (名 + ": " + 值 + "\r\n").encode("utf-8")
    请求 += b"\r\n"
    if 体:
        请求 += 体
    写入器.write(请求)
    await 写入器.drain()
    状态, 体字节, _ = await 读响应(读取器)
    if 关闭:
        写入器.close()
        try:
            await 写入器.wait_closed()
        except Exception:
            pass
    return 状态, 体字节, 读取器, 写入器


async def 复用发请求(读取器, 写入器, 端口, 方法="GET", 路径="/", 头=None, 体=None):
    """keep-alive：在已建立的连接上再发一笔，返回 [状态码, 响应体字节]。"""
    请求 = (方法 + " " + 路径 + " HTTP/1.1\r\nHost: 127.0.0.1\r\n").encode("utf-8")
    for 名, 值 in (头 or {}).items():
        请求 += (名 + ": " + 值 + "\r\n").encode("utf-8")
    请求 += b"\r\n"
    if 体:
        请求 += 体
    写入器.write(请求)
    await 写入器.drain()
    状态, 体字节, _ = await 读响应(读取器)
    return 状态, 体字节


