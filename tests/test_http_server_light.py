# 判据 2：并发 10 连接（时序 + 峰值双断言）
# ===========================================================================
def test_并发10连接():
    """10 个慢请求并行完成：总耗时 < 1.2s（串行需 2.5s），并发峰值 == 10。

    反跑点：处理循环 的「创建任务(处理连接(...))」改成「等待 处理连接(...)」
    后，本断言 总耗时 < 1.2s 立即立红（实测串行 2.5s+）。
    """

    async def 主体(服务器, 端口):
        开始 = time.monotonic()
        结果们 = await asyncio.gather(*(发请求(端口) for _ in range(10)))
        总耗时 = time.monotonic() - 开始
        for 状态, _, _, _ in 结果们:
            assert 状态 == 200
        assert 总耗时 < 1.2, "并发 10 请求应并行完成，实际耗时 %s 秒" % 总耗时
        assert 服务器.并发峰值 == 10, "10 连接应同时进入处理器，峰值 %s" % 服务器.并发峰值
        assert 服务器.完成数 == 10

    跑服务端(慢处理器, 主体)


