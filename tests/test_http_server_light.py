async def 回显处理器(请求):
    """把请求体原文回显（chunked 解码判据靠它验证）。"""
    return {
        "状态": 200,
        "头": {"Content-Type": "text/plain; charset=utf-8"},
        "体": 请求["体"].decode("utf-8"),
    }


async def 慢处理器(请求):
    """模拟慢业务：每笔请求睡 0.25s（并发时序判据的杠杆）。"""
    await asyncio.sleep(0.25)
    return {"状态": 200, "头": {}, "体": "slow-ok"}


# ---------------------------------------------------------------------------
# 主管：起服务端 → 跑主体 → 停服务端（端口一律内核分配，bind 0）
# ---------------------------------------------------------------------------
def 跑服务端(处理器, 主体, 超时=5.0):
    """同步入口：内部 asyncio.run。服务器与循环任务都保证清理。"""
    服务器 = HTTP服务端(处理器, 超时)

    async def 主管():
        端口 = 服务器.端口()
        循环任务 = asyncio.create_task(处理循环(服务器))
        try:
            await 主体(服务器, 端口)
        finally:
            服务器.停止()
            循环任务.cancel()
            try:
                await 循环任务
            except asyncio.CancelledError:
                pass

    asyncio.run(主管())


