def test_chunked请求体():
    """Transfer-Encoding: chunked 的 POST，处理器必须收到解码后的完整体。

    反跑点：把 读分块体 的「大小 == 0: 返回 累计」改成提前返回，
    或把十六进制解析改成十进制，本断言立即立红。
    """

    async def 主体(服务器, 端口):
        分块 = b"5\r\nhello\r\n8\r\n chunked\r\n0\r\n\r\n"
        状态, 体字节, _, _ = await 发请求(
            端口, "POST", "/upload", {"Transfer-Encoding": "chunked"}, 分块
        )
        assert 状态 == 200
        assert 体字节 == b"hello chunked"

    跑服务端(回显处理器, 主体)


