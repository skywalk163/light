# 判据 6：反跑 —— 并发改串行，串行确实慢
# ===========================================================================
def test_并发改串行_串行确实慢():
    """反跑的可执行形态：并发模式=假（等价于把 处理循环 的 创建任务 改成
    等待 处理连接），同样 10 连接串行执行总耗时 >= 2.0s、并发峰值 == 1。

    若某天服务端的并发语义被改坏（退化成串行而不自知），判据 2 的
    「总耗时 < 1.2s」会立红 —— 本条证明「开关敏感」，让反跑可机械复现。
    """

    async def 主体(服务器, 端口):
        服务器.并发模式 = False
        开始 = time.monotonic()
        结果们 = await asyncio.gather(*(发请求(端口) for _ in range(10)))
        总耗时 = time.monotonic() - 开始
        for 状态, _, _, _ in 结果们:
            assert 状态 == 200
        assert 总耗时 >= 2.0, "串行 10 × 0.25s 应 >= 2.0s，实际 %s 秒" % 总耗时
        assert 服务器.并发峰值 == 1, "串行模式下并发峰值应为 1，实际 %s" % 服务器.并发峰值

    跑服务端(慢处理器, 主体)


