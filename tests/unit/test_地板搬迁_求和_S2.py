# §2 本机平台的 C long 上界
# =============================================================================

def _探平台长整上限():
    """[2**31, 1e16, 1.0, -1e16]：

    C long 是 32 位时，2**31 出不了整数快路径 → 切出结果还是 int → 补偿路径整段
    被跳过 → 其后全程朴素 → 2147483648.0；
    C long 是 64 位时，2**31 留在快路径 → 切出结果是 float → 走补偿 → 2147483649.0。

    **只在宿主 >= 3.12 时有判别力**：C long 宽度是靠"补偿量有没有被留住"暴露出来的，
    宿主不走补偿时两种宽度给同一个 double（都是 2147483648.0），sum() 的输出里
    根本没有这个信息。所以 3.11 宿主上改用 struct.calcsize("l") 直接量。
    """
    探 = sum([2 ** 31, 1e16, 1.0, -1e16])
    if repr(探) == repr(2147483648.0):
        return _LLP64上界
    if repr(探) == repr(2147483649.0):
        return _LP64上界
    raise AssertionError("认不出本平台的 C long 上界：探针值=%r" % (探,))


_按C类型量上界 = (1 << (8 * struct.calcsize("l") - 1)) - 1
_平台上界 = _探平台长整上限() if _本机启用补偿 else _按C类型量上界


def test_平台上界探针只有两种结果():
    assert _平台上界 in (_LLP64上界, _LP64上界)


def test_两种上界口径互证():
    """sum() 探针与 struct.calcsize("l") 必须给同一个答案（3.12+ 宿主上才两者都可用）。"""
    assert _按C类型量上界 in (_LLP64上界, _LP64上界)
    if _本机启用补偿:
        assert _探平台长整上限() == _按C类型量上界
    else:
        # 3.11 宿主：探针没有判别力，实测两种宽度都给 2147483648.0 —— 把这件事本身钉住。
        assert repr(sum([2 ** 31, 1e16, 1.0, -1e16])) == "2147483648.0"


