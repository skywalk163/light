def test_平均值两种模式的取证():
    """搬迁前 平均值([0.1]*10) 走朴素累加，给 0.09999999999999999；
    补偿模式给 0.1。两种模式各钉一条，与宿主版本无关；再钉住本机 sum 落在哪一侧。"""
    朴素总和 = 0
    for x in [0.1] * 10:
        朴素总和 = 朴素总和 + x
    assert repr(朴素总和 / 10) == "0.09999999999999999"
    assert repr(L平均值([0.1] * 10, _LP64上界, True)) == "0.1"
    assert repr(L平均值([0.1] * 10, _LP64上界, False)) == "0.09999999999999999"
    assert repr(sum([0.1] * 10) / 10) == (
        "0.1" if _本机启用补偿 else "0.09999999999999999")
