_LLP64上界 = 2147483647

# 宿主 CPython 是否走 Neumaier 补偿（3.12 起）——光明侧 `求和` 第三参。
# 这不是"随便选个开关"：oracle 是**本机内置 sum()**，而 sum() 的浮点语义是版本相关的，
