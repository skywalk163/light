# 两边都要绿，就只能让判据跟着宿主走 —— 而不是把宿主假设成 3.12+。
_本机启用补偿 = sys.version_info >= (3, 12)


def _宿主实参(数据, 上界=None):
    """把「本机口径」翻成光明侧的实参列表。

    上界=None 表示"用光明侧默认（LP64）"。只有在需要传第三参时才必须把第二参一起写出来
    （它是位置参），此时补默认值 _LP64上界，语义与不传一致。
    """
    if _本机启用补偿:
        return [数据] if 上界 is None else [数据, 上界]
    return [数据, _LP64上界 if 上界 is None else 上界, False]


def L求和宿主(数据, 上界=None):
    """按本机口径（平台 C long 宽度 + 版本补偿语义）调光明侧 求和。"""
    return L求和(*_宿主实参(list(数据), 上界))


def L平均值宿主(数据, 上界=None):
    return L平均值(*_宿主实参(list(数据), 上界))



