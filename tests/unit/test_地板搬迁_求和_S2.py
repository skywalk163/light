"""
test_地板搬迁_求和_S2.py —— 「地板搬迁」等价性判据：stdlib/builtins.py:1055 的
`求和`（函数体就一句 `return sum(数据)`）要转发到 stdlib/列表工具.light 的 `求和`，
那么光明侧必须与 CPython 内置 `sum()` **逐位（bit-exact）等价**，包括：
返回值的每一个二进制位（用 repr 比）、返回值的**类型**（全 int 列表必须回 int）、
以及异常类型。

oracle 口径（硬要求）：本文件的 oracle 就是**内联的内置 `sum(数据)`**——它本身就是
等价目标，允许直接用。**不许** `from builtins import 求和` 再自比（转发做完后那就是
自己跟自己比，测试永远绿）。

被测侧：经光明导入钩子加载 stdlib/列表工具.light（引导方式照抄
tests/unit/test_地板搬迁_JSON_S2.py:27-33）。`test_被测侧确实来自光明文件` 是守卫：
若 `import 列表工具` 落到同目录的 列表工具.py 上，本轮所有对拍都失去意义。

===============================================================================
为什么朴素累加不行（实测 CPython 3.14.7，Windows/MSVC 64 位）
===============================================================================
CPython 自 3.12（gh-100425）起，sum() 对浮点走 Neumaier 补偿求和，不再朴素累加：

    样本                       sum()                  朴素左到右累加
    [1e16, 1.0, -1e16]         1.0                    0.0
    [1.0, 1e100, 1.0, -1e100]  2.0                    0.0
    [0.1]*10                   1.0                    0.9999999999999999
    [0.1]*100                  10.0                   9.99999999999998
    [0.1, 0.2, 0.3]            0.6                    0.6000000000000001
    [1e-323, 1e308, -1e308, 1e-323]  2e-323           1e-323

===============================================================================
一处**平台相关**的已知不等价（如实记录，不假装等价）
===============================================================================
CPython 整数快路径里，单个元素能否留在快路径，判据是 `PyLong_AsLongAndOverflow`
即 **C long** 装得下（累加值的上限另算，是 PY_SSIZE_T_MAX）。C long 的宽度平台相关：

    LP64（Linux / FreeBSD 64 位）  long 64 位 → 上界 9223372036854775807
    LLP64（Windows / MSVC）        long 32 位 → 上界 2147483647

光明侧问不到 sizeof(long)（只有 struct / ctypes 这类 **Python 模块**能问，而
stdlib/列表工具.light 里一个 Python 直调都不许有，见 tools/ci/python_direct_calls.py
的逐文件棘轮），所以 `求和` 把这个门槛做成了显式第二参 `长整上限`，默认取 LP64 值。

于是在 Windows 上，「|int 元素| ≥ 2**31 且其后还有会发生抵消的浮点」这个窗口里，
默认参数（LP64 上界）的光明 `求和` 与本机 `sum()` **不等价**。
本文件把这件事分成三条用例钉死：
  - test_平台窗口_传宿主口径则逐位等价：把本机口径（上界 + 补偿开关）传进去 → 必须
    逐位相等（证明算法本身两个平台 × 两个版本都能复刻）；
  - test_平台窗口_默认参数就是LP64加补偿：默认值本身是契约，改了就红；
  - test_平台窗口_两种上界的分歧列取证：把「哪些样本上两种上界给不同 double」这张
    实测表钉死，且这条与宿主平台/版本都无关。

===============================================================================
一处**版本相关**的已知差异（CI runner 是 3.11，开发机是 3.14）
===============================================================================
sum() 的浮点语义自 3.12 起才是 Neumaier 补偿，3.11 及更早是朴素累加。也就是说
「与内置 sum() 逐位等价」这句话的含义**随宿主版本变**。所以 `求和` 把补偿开关做成了
显式第三参 `启用补偿`（默认真 = 3.12+ 语义），由 builtins.py 按
`sys.version_info >= (3, 12)` 算出来传进去；本文件同样按宿主口径调用（见 _宿主实参），
于是 3.11 宿主与 3.14 宿主上都与**该宿主的** sum() 逐位等价。
实测两侧数值（3.11.15 vs 3.14.7，同一份样本）：
    [0.1, 0.2, 0.3]     3.11: 0.6000000000000001   3.12+: 0.6
    [1e16, 1.0, -1e16]  3.11: 0.0                  3.12+: 1.0
把宿主假设成 3.12+ 就是本文件第一版犯的错：开发机绿、CI（3.11）36 条红。
"""
