# §1 逐位比较工具：不许 approx / round
# =============================================================================

def 逐位相同(甲, 乙):
    """类型必须相同 + repr 必须逐字相同。

    用 repr 而不是 `==`：`nan == nan` 为假、`-0.0 == 0.0` 为真，两头都会误判。
    repr 能把 nan / -0.0 / 各位有效数字全部区分开。
    """
    if type(甲) is not type(乙):
        return False
    return repr(甲) == repr(乙)


def 对拍(样本, 上界=None):
    """返回 (光明结果, oracle结果)；两边都要么给值、要么抛同类型异常。

    光明侧一律按**本机口径**调用（见 _宿主实参）：oracle 是本机内置 sum，
    而 sum 的浮点语义随宿主版本变，所以判据必须跟着宿主走。
    """
    数据 = list(样本)
    try:
        光明 = ("值", L求和宿主(数据, 上界))
    except BaseException as e:          # noqa: BLE001 - 要比异常类型，必须全抓
        光明 = ("异常", type(e))
    try:
        神谕 = ("值", sum(list(数据)))    # ← oracle：内联的内置 sum
    except BaseException as e:          # noqa: BLE001
        神谕 = ("异常", type(e))
    return 光明, 神谕


def 断言等价(样本, 上界=None):
    光明, 神谕 = 对拍(样本, 上界)
    assert 光明[0] == 神谕[0], (
        "一侧给值一侧抛异常：样本=%r 光明=%r oracle=%r" % (样本, 光明, 神谕))
    if 光明[0] == "异常":
        assert 光明[1] is 神谕[1], (
            "异常类型不同：样本=%r 光明=%s oracle=%s" % (样本, 光明[1].__name__, 神谕[1].__name__))
        return
    assert 逐位相同(光明[1], 神谕[1]), (
        "不逐位相等：样本=%r 光明=%r(%s) oracle=%r(%s)"
        % (样本, 光明[1], type(光明[1]).__name__, 神谕[1], type(神谕[1]).__name__))


