def _断言非空壳(模块, 导出名):
    """只读反跑检查：仓库内 stdlib/模块.light 必须是真实现（含段落/函数/类），不得退回 decl-0 空壳。"""
    path = _模块路径[模块]
    with open(path, 'r', encoding='utf-8') as f:
        src = f.read()
    assert ('段落 ' in src) or ('函数 ' in src) or ('类 ' in src), \
        f'{模块}.light 疑似退回空壳：无段落/函数/类主体'
    导出行 = [ln for ln in src.splitlines() if ln.strip().startswith('导出 ')]
    assert 导出行, f'{模块}.light 缺少导出声明'
    for 名 in 导出名.split():
        assert any((' ' + 名 + ' ') in (' ' + ln + ' ') for ln in 导出行), \
            f'{模块}.light 导出清单缺少 {名}'


def _反跑_空壳(模块, 导出名, 导入名, 调用, 期望片段='decl 0 空壳'):
    """空壳反跑：在 OS 临时目录放 decl-0 空壳 .light + 同名 .py 影子 + 导入方，
    编译必须报 NativeImportError（decl 0 空壳），验证「改回空壳 → 判红」机制。
    不触碰仓库 stdlib 文件（避免对工作树写入）。"""
    from llvm.compiler import NativeImportError, compile_light_typed
    with _tempfile.TemporaryDirectory(prefix='_taskT6c_') as d:
        空壳 = '# 纯光明实现\n# 空壳测试\n导出 ' + 导出名 + '。\n'
        with open(os.path.join(d, 模块 + '.light'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(空壳)
        with open(os.path.join(d, 模块 + '.py'), 'w', encoding='utf-8', newline='\n') as f:
            f.write('# 同名 Python 实现（影子）\n')
        code = ('从 ' + 模块 + ' 导入 ' + 导入名 + '\n'
                '段落 主:\n'
                '  输出(' + 调用 + ')\n')
        src = os.path.join(d, '主.light')
        with open(src, 'w', encoding='utf-8', newline='\n') as f:
            f.write(code)
        with pytest.raises(NativeImportError, match=期望片段):
            compile_light_typed(src, os.path.join(d, '产物'), optimize_level=0)


