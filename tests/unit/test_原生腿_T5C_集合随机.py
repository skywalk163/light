def _随机oracle():
    """与 _随机程序 逐调用镜像的 CPython random.Random(42) 序列。"""
    r = random.Random(42)
    行 = []
    行.append(str(r.randint(1, 6)))
    行.append(str(r.randint(1, 6)))
    行.append(str(r.randint(1, 6)))
    行.append(str(r.randrange(0, 10)))
    行.append(str(r.randrange(0, 10)))
    行.append(str(r.randrange(0, 10)))
    行.append(str(int(r.uniform(0, 1) * _TWO53)))
    行.append(str(int(r.uniform(0, 10) * _TWO53)))
    行.append(str(r.choice([10, 20, 30])))
    行.append(str(r.choice([10, 20, 30])))
    行.append(str(r.choice([10, 20, 30])))
    行.append(",".join(str(x) for x in r.choices([1, 2, 3, 4], k=6)))
    行.append(",".join(str(x) for x in r.choices([10, 20, 30], weights=[1, 1, 2], k=5)))
    行.append("真" if r.randrange(2) == 0 else "假")
    行.append("真" if r.randrange(2) == 0 else "假")
    行.append("真" if r.randrange(2) == 0 else "假")
    行.append("真" if r.randrange(2) == 0 else "假")
    池 = [1, 2, 3, 4, 5]
    r.shuffle(池)
    行.append(",".join(str(x) for x in 池))
    池2 = [11, 22, 33, 44, 55, 66]
    r.shuffle(池2)
    行.append(",".join(str(x) for x in 池2))
    行.append(",".join(str(x) for x in r.sample(range(10), 4)))
    行.append(",".join(str(x) for x in r.sample(range(100), 10)))
    _字母表 = string.ascii_letters + string.digits
    行.append("".join(_字母表[r.randrange(62)] for _ in range(8)))
    for _ in range(3):
        行.append(_字母表[r.randrange(62)])
    行.append(r.getrandbits(32).to_bytes(4, "little").hex())
    行.append(str(int(r.random() * _TWO53)))
    行.append(str(int(r.random() * _TWO53)))
    for _ in range(4):
        行.append(str(int(r.gauss(0, 1) * _TWO53)))
    _口令集 = string.ascii_letters + string.digits + "!@#$%^&*"
    行.append("".join(_口令集[r.randrange(len(_口令集))] for _ in range(12)))
    行.append(str(r.randint(5, 9)))
    行.append(str(r.randint(5, 9)))
    return 行


def test_随机_固定种子42逐位对拍_O0():
    rc, 光明行, err = _编译并运行(_随机程序, optimize_level=0)
    assert rc == 0, "O0 崩溃 rc=%d err=%s" % (rc, err[:300])
    oracle = _随机oracle()
    assert len(光明行) == len(oracle) + 3, (
        "行数不同: 光明=%d oracle=%d\n光明=%r\noracle=%r" %
        (len(光明行), len(oracle), 光明行, oracle))
    for i, (a, b) in enumerate(zip(光明行[:len(oracle)], oracle)):
        assert a == b, "第 %d 行不一致: 光明=%r oracle=%r" % (i, a, b)
    # 末尾三行为安全令牌/URL令牌/UUID：仅格式断言（.py 走 os.urandom，不对拍流）
    assert re.fullmatch(r"[0-9a-f]{8}", 光明行[len(oracle)]), (
        "安全随机令牌格式: %r" % 光明行[len(oracle)])
    assert re.fullmatch(r"[A-Za-z0-9_-]{4}", 光明行[len(oracle) + 1]), (
        "URL令牌格式: %r" % 光明行[len(oracle) + 1])
    assert re.fullmatch(
        r"[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}",
        光明行[len(oracle) + 2]), "UUID 格式/版本: %r" % 光明行[len(oracle) + 2]


