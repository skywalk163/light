# ── 列表过滤 测试 ────────────────────────────────────────────────────────────
# 谓词函数：大于2
def _大于二(x):
    return x > 2


# 谓词函数：偶数
def _偶数(x):
    return x % 2 == 0


_过滤用例 = [
    # (输入列表, 谓词, 期望结果, 描述)
    ([1, 2, 3, 4, 5], _大于二, [3, 4, 5], "过滤大于2的元素"),
    ([], _大于二, [], "空列表过滤"),
    ([1, 2], _大于二, [], "全部不满足"),
    ([3, 4, 5], _大于二, [3, 4, 5], "全部满足"),
    ([1, 2, 3, 4], _偶数, [2, 4], "过滤偶数"),
    ([0, -1, -2, 3], _偶数, [0, -2], "含负数的偶数过滤"),
]


@pytest.mark.parametrize("输入,谓词,期望,描述", _过滤用例)
def test_列表过滤_正例(输入, 谓词, 期望, 描述):
    原表 = copy.deepcopy(输入)
    结果 = 列表模块.列表过滤(输入, 谓词)
    assert 结果 == 期望, f"列表过滤 - {描述}: 期望 {期望}, 实得 {结果}"
    # 原列表不被修改
    assert 输入 == 原表, "列表过滤不应修改原列表"


def test_列表过滤_反例_空谓词报错():
    with pytest.raises(TypeError):
        列表模块.列表过滤([1, 2, 3], None)


def test_列表过滤_反谓词类型():
    """谓词不是函数时应报错"""
    with pytest.raises(TypeError):
        列表模块.列表过滤([1, 2, 3], "不是函数")


