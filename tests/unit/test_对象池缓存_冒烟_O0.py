import os
import subprocess
import sys
import tempfile

_REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_REPO, "src"))


def _编译并运行(code, optimize_level=0):
    """用原生腿 compile_light_typed 编译并运行，返回 (rc, stdout行列表, stderr)。"""
    from llvm.compiler import compile_light_typed
    with tempfile.TemporaryDirectory(prefix="_taskCIC_") as d:
        src = os.path.join(d, "主.light")
        with open(src, "w", encoding="utf-8", newline="\n") as f:
            f.write(code)
        exe = compile_light_typed(src, os.path.join(d, "产物"),
                                  optimize_level=optimize_level)
        r = subprocess.run([exe], capture_output=True, timeout=120)
        out = r.stdout.decode("utf-8", errors="replace").replace("\r", "").strip()
        err = r.stderr.decode("utf-8", errors="replace")
        return r.returncode, out.split("\n") if out else [], err


def test_对象池缓存_最小复现_写入取回_O0():
    """反跑判据测试：最小复现——放入两个值，LIFO 取回，值必须真正写进池槽。

    对应任务书「最小化复现」三行核心（对象池放入("a") → 放入("b") → 对象池获取），
    使用 stdlib 真实 API（对象池获取 只接受 池 一个参数，LIFO 取最近放入）。
    """
    code = (
        "从 对象池缓存 导入 创建对象池 对象池放入 对象池获取\n"
        "段落 主:\n"
        "  设 池 为 创建对象池(空, 10)\n"
        "  设 空值 为 对象池放入(池, \"a\")\n"
        "  设 空值 为 对象池放入(池, \"b\")\n"
        "  输出(转文本(对象池获取(池)))\n"   # 期望 b（LIFO 取最近放入）
        "  输出(转文本(对象池获取(池)))\n"   # 期望 a
        "  输出(转文本(对象池获取(池)))\n"   # 期望 空（再取为空）
    )
    rc, 光明行, err = _编译并运行(code, optimize_level=0)
    assert rc == 0, "O0 崩溃 rc=%d err=%s" % (rc, err[:400])
    assert 光明行 == ["b", "a", "空"], \
        "放入的值没写进池槽（R12B 回归）: 光明=%r 期望=%r" % (光明行, ["b", "a", "空"])


