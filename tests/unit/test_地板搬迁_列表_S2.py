def test_副作用段落_返回None且原地改调用方列表(名字, 初值, 其余入参, 期望):
    光明表 = copy.deepcopy(初值)
    原版表 = copy.deepcopy(初值)
    光明表身份 = id(光明表)
    原版表身份 = id(原版表)

    光明返回 = getattr(光明, 名字)(光明表, *copy.deepcopy(其余入参))
    原版返回 = getattr(原版, 名字)(原版表, *copy.deepcopy(其余入参))

    # ① 返回值必须是 None，与 Python 版一致（别悄悄返回改好的新列表）
    assert 光明返回 is None, ("%s 光明版返回了 %r 而不是 None —— 一旦它返回新列表，"
                             "调用方拿返回值就跑通了，原地语义会静默丢掉"
                             % (名字, 光明返回))
    assert 原版返回 is None, "%s Python 版返回了 %r 而不是 None" % (名字, 原版返回)

    # ② 调用方手里那个列表对象**本身**被改了。
    #    光明表 这个名字从未被重新绑定，所以它此刻等于期望值，只可能是原地改的结果；
    #    若实现改成「返回新列表」，光明表 会仍是初值，这里当场红。
    assert 光明表 == 期望, ("%s%r 之后调用方的列表应为 %r，实为 %r —— 副作用没落到入参上"
                           % (名字, 其余入参, 期望, 光明表))
    assert 原版表 == 期望, ("%s%r 之后 Python 版调用方的列表应为 %r，实为 %r"
                           % (名字, 其余入参, 期望, 原版表))
    assert 光明表 == 原版表
    # ③ 还得是同一个对象（没有偷偷把入参换成新对象）
    assert id(光明表) == 光明表身份
    assert id(原版表) == 原版表身份


