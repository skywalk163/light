# ── 3. 排序稳定性：相等键必须保持原序 ──────────────────────────────────────────
class _只按键比较:
    """只定义 `__lt__`（list.sort 只用 `<`），键相等时元素彼此「不小于」。

    用元组做不到这件事：`(1, "甲") < (1, "丙")` 会拿第二个元素继续比，
    等于给了排序一个 tie-break，稳定性就测不出来了。
    """

    def __init__(self, 键, 标记):
        self.键 = 键
        self.标记 = 标记

    def __lt__(self, 其他):
        return self.键 < 其他.键

    def __repr__(self):
        return "元(%r,%r)" % (self.键, self.标记)


def _造稳定性样本():
    return [_只按键比较(1, "甲"), _只按键比较(0, "乙"),
            _只按键比较(1, "丙"), _只按键比较(0, "丁")]


def test_列表排序_稳定性_正序时相等键保持原序():
    光明表 = _造稳定性样本()
    原版表 = _造稳定性样本()
    光明.列表排序(光明表, False)
    原版.列表排序(原版表, False)
    assert [元.标记 for 元 in 光明表] == ["乙", "丁", "甲", "丙"]
    assert [元.标记 for 元 in 原版表] == ["乙", "丁", "甲", "丙"]


def test_列表排序_稳定性_反向时相等键仍保持原序():
    """`reverse=True` 不是「排完再倒过来」：Python 保证反向排序同样稳定。

    若实现写成 `表.sort()` 再 `表.reverse()`，相等键会被倒序（丙 在 甲 前），
    这条就红 —— 这正是「接反 reverse」之外的第二种典型错译。
    """
    光明表 = _造稳定性样本()
    原版表 = _造稳定性样本()
    光明.列表排序(光明表, True)
    原版.列表排序(原版表, True)
    assert [元.标记 for 元 in 光明表] == ["甲", "丙", "乙", "丁"]
    assert [元.标记 for 元 in 原版表] == ["甲", "丙", "乙", "丁"]


