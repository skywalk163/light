@pytest.mark.parametrize("名字, 入参, 异常类型", _错误用例)
def test_错误路径_两版抛同一个异常类型(名字, 入参, 异常类型):
    with pytest.raises(异常类型) as 光明信息:
        getattr(光明, 名字)(*copy.deepcopy(入参))
    with pytest.raises(异常类型) as 原版信息:
        getattr(原版, 名字)(*copy.deepcopy(入参))
    # 不只是「都属于 异常类型」，得是同一个具体类（IndexError vs 其子类会被这条抓到）
    assert type(光明信息.value) is type(原版信息.value)


def test_列表排序抛TypeError后不许把列表改成乱序之外的样子():
    """排序中途抛异常时，Python 的 list.sort 会把列表置空再恢复，最终元素集合不变。

    这条守的是「搬迁时自己写了个冒泡，抛异常后列表只排了一半」——那种实现
    错误类型对得上，但调用方拿到的是半排好的列表，与 Python 版不一致。
    """
    光明表 = [3, 1, "甲", 2]
    原版表 = [3, 1, "甲", 2]
    with pytest.raises(TypeError):
        光明.列表排序(光明表, False)
    with pytest.raises(TypeError):
        原版.列表排序(原版表, False)
    assert 光明表 == 原版表
    assert sorted(map(repr, 光明表)) == sorted(map(repr, [3, 1, "甲", 2]))


# ── 5. 冻结的口径差：默认参数只在 Python 侧 ────────────────────────────────────
def test_默认参数只留在Python签名侧():
    """光明段落收满参（负数默认值在光明里解析失败），默认值由 builtins.py 承担。

    这是本次搬迁**唯一**的口径差，且是语言层限制而非疏漏。正面断言它：
    - Python 版少传参走默认（索引=-1 / 反向=False）；
    - 光明版少传参是 TypeError。
    以后谁想「对齐」，会先撞上这条测试，从而看到上面的理由。
    """
    表 = [1, 2, 3]
    assert 原版.列表弹出(表) == 3          # 默认 索引=-1
    assert 表 == [1, 2]

    表二 = [2, 1]
    assert 原版.列表排序(表二) is None     # 默认 反向=False
    assert 表二 == [1, 2]

    with pytest.raises(TypeError):
        光明.列表弹出([1, 2])
    with pytest.raises(TypeError):
        光明.列表排序([2, 1])

    # 收满参时两版逐字等价（默认值等价物 -1 / False 显式传进去）
    甲 = [1, 2, 3]
    乙 = [1, 2, 3]
    assert 光明.列表弹出(甲, -1) == 原版.列表弹出(乙, -1)
    assert 甲 == 乙
    丙 = [2, 1]
    丁 = [2, 1]
    assert 光明.列表排序(丙, False) == 原版.列表排序(丁, False)
    assert 丙 == 丁
