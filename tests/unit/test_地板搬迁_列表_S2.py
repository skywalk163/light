# -*- coding: utf-8 -*-
"""地板搬迁差分测试（第九轮 S2 · C 路 · 列表组）：
`stdlib/内置核心列表.light` 的 10 个段落 vs `stdlib/builtins.py` 的 Python 原版，逐条对跑。

为什么是差分测试而不是「光明版自己对着期望值跑一遍」
------------------------------------------------------
地板搬迁的验收标准是**逐字等价**：`builtins.py` 里那 10 个函数被每一份光明产物
站着用（`src/code_generator.py` 的序言按路径把 builtins.py 加载进去），任何一处
语义漂移都会在产物侧变成「跟光明毫无字面关系」的怪错。所以每条用例都同时喂给
两版，断三件事：光明版 == 期望、Python 版 == 期望、两版彼此相等。
只断前者会漏「期望值本身抄错了」，只断后者会漏「两版一起错」。

四条有副作用的段落（列表追加 / 列表插入 / 列表排序 / 列表反转）另有两条硬判据
------------------------------------------------------------------------------
Python 原版靠 `列表.append(元素)` 这种**原地改入参**来干活，返回 None。
搬迁时最容易发生的退化是「改成 `return 表 + [元素]` 返回新列表」——那样
`列表追加(甲, 1)` 的调用方手里的 `甲` 一个元素都不会多，而单看返回值的测试全绿。
所以：
  ① 返回值必须 `is None`；
  ② 调用方传进去的那个列表对象**本身**被改了（同一批初值分别喂两版，最后两个
     列表逐元素相等），且 `id()` 没变（不是偷偷换了个新对象回来）。

已知且**故意保留**的口径差（唯一一条，见 test_默认参数只留在Python签名侧）
--------------------------------------------------------------------------
`列表弹出(列表, 索引=-1)` 与 `列表排序(列表, 反向=False)` 的默认值只写在
builtins.py 的 Python 签名里：光明侧 `接收 x, y=-1:` 解析失败（期望冒号得到减号），
负数默认值写不出来。所以光明段落收满参，默认值由 Python 侧承担。
这条差是**冻结的契约**，本文件正面断言它，免得后人以为是漏洞顺手「修」掉。
"""
