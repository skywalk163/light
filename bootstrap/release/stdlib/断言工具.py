_通过数 = 0
_失败数 = 0
_当前套件名 = ""
_失败列表 = []


def _测试框架_断言相等(实际: Any, 期望: Any, 消息: str = "") -> None:
    """测试框架用断言相等（计数版，不抛异常）"""
    if 实际 == 期望:
        global _通过数
        _通过数 += 1
    else:
        global _失败数
        _失败数 += 1
        _失败列表.append(消息 or f"期望 {期望}, 实际 {实际}")


def _测试框架_断言不等(实际: Any, 期望: Any, 消息: str = "") -> None:
    """测试框架用断言不等（计数版，不抛异常）"""
    if 实际 != 期望:
        global _通过数
        _通过数 += 1
    else:
        global _失败数
        _失败数 += 1
        _失败列表.append(消息 or f"期望不相等, 但都是 {实际}")


def _测试框架_断言为真(值: Any, 消息: str = "") -> None:
    """测试框架用断言为真（计数版，不抛异常）"""
    if 值:
        global _通过数
        _通过数 += 1
    else:
        global _失败数
        _失败数 += 1
        _失败列表.append(消息 or f"期望为真, 实际 {值}")


def _测试框架_断言为假(值: Any, 消息: str = "") -> None:
    """测试框架用断言为假（计数版，不抛异常）"""
    if not 值:
        global _通过数
        _通过数 += 1
    else:
        global _失败数
        _失败数 += 1
        _失败列表.append(消息 or f"期望为假, 实际 {值}")


def _测试框架_断言为空(值: Any, 消息: str = "") -> None:
    """测试框架用断言为空（计数版，不抛异常）"""
    if len(值) == 0:
        global _通过数
        _通过数 += 1
    else:
        global _失败数
        _失败数 += 1
        _失败列表.append(消息 or f"期望为空, 实际长度 {len(值)}")


def _测试框架_断言不为空(值: Any, 消息: str = "") -> None:
    """测试框架用断言不为空（计数版，不抛异常）"""
    if len(值) > 0:
        global _通过数
        _通过数 += 1
    else:
        global _失败数
        _失败数 += 1
        _失败列表.append(消息 or "期望不为空")


def _测试框架_断言近似(实际: float, 期望: float, 精度: float = 1e-9, 消息: str = "") -> None:
    """测试框架用断言近似（计数版，不抛异常）"""
    if abs(实际 - 期望) <= 精度:
        global _通过数
        _通过数 += 1
    else:
        global _失败数
        _失败数 += 1
        _失败列表.append(消息 or f"期望 {期望}, 实际 {实际}, 精度 {精度}")


def 测试开始(名称: str) -> None:
    """开始测试套件"""
    global _通过数, _失败数, _当前套件名, _失败列表
    _通过数 = 0
    _失败数 = 0
    _当前套件名 = 名称
    _失败列表 = []
    print(f"开始测试：{名称}")


def 测试结束() -> None:
    """结束测试套件并输出结果"""
    总数 = _通过数 + _失败数
    print(f"测试完成：{_当前套件名}")
    print(f"通过：{_通过数}/{总数}")
    if _失败数 > 0:
        print(f"失败：{_失败数}/{总数}")
        for 失败 in _失败列表:
            print(f"  - {失败}")
    else:
        print("全部通过！")


def 测试运行(测试函数: Callable) -> None:
    """运行单个测试函数"""
    try:
        测试函数()
    except Exception as e:
        global _失败数
        _失败数 += 1
        _失败列表.append(str(e))